#!/usr/bin/env python3
"""Knowledge-base manifest: what is in docs/knowledge-base, where each file came from,
and whether the copy on disk still matches what the manifest recorded.

    kb_manifest.py generate            write KNOWLEDGE-MANIFEST.yaml (and print a summary)
    kb_manifest.py validate            exit 1 if files were added/removed/changed since the manifest
    kb_manifest.py validate --json     machine-readable drift report

Each entry records the relative path, size, sha256, the source header the document itself declares
(`source_db:`/`source:`/`generated_date:`/`Generated:` lines in its first 20 lines) and the git
revision that last touched it. The manifest header records the repository revision and generator
version so a reader knows how old the snapshot is. Stdlib only; no Snowflake needed.
"""
import hashlib
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
KB = os.path.join(ROOT, "docs", "knowledge-base")
MANIFEST = os.path.join(KB, "KNOWLEDGE-MANIFEST.yaml")
GENERATOR_VERSION = "1"
HEADER_RE = re.compile(r"^\s*(?:\*\*)?(source_db|source|generated_date|generated|Generated|Source|Database)\s*[:：]\s*(?:\*\*)?\s*(.+?)\s*$")


def read_normalised(path):
    """File bytes with CRLF folded to LF, so a Windows checkout (core.autocrlf) hashes like Linux."""
    with open(path, "rb") as f:
        return f.read().replace(b"\r\n", b"\n")


def sha256(path):
    return hashlib.sha256(read_normalised(path)).hexdigest()


def declared_source(path):
    if not path.endswith((".md", ".yaml", ".yml", ".txt")):
        return {}
    out = {}
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            for _ in range(20):
                line = f.readline()
                if not line:
                    break
                m = HEADER_RE.match(line)
                if m:
                    out.setdefault(m.group(1).lower().replace("generated_date", "generated"), m.group(2))
    except OSError:
        pass
    return out


KIND_BY_AREA = {"Archive": "archive", "REPORTS": "report", "DOCUMENTATION": "report", "_REGEN": "staging", "PROMPTS": "pointer"}


def kind_of(rel):
    """current = read by agents; archive/report/staging/pointer = skip when answering questions."""
    return KIND_BY_AREA.get(rel.split("/")[0], "current")


def git(*args):
    try:
        return subprocess.check_output(["git", "-C", ROOT] + list(args), text=True, stderr=subprocess.DEVNULL).strip()
    except (subprocess.CalledProcessError, OSError):
        return ""


def uncommitted():
    out = git("status", "--porcelain", "--untracked-files=all", "--", os.path.relpath(KB, ROOT))
    return sum(1 for line in out.splitlines()
               if line.strip() and not line.rstrip().endswith("/" + os.path.basename(MANIFEST)))


def last_commit_map():
    """path -> short sha of the last commit touching it, one git call for the whole KB."""
    log = git("log", "--name-only", "--format=%x00%h", "--", "docs/knowledge-base")
    out, sha = {}, None
    for line in log.splitlines():
        if line.startswith("\x00"):
            sha = line[1:]
        elif line and sha and line not in out:
            out[line] = sha
    return out


def scan():
    commits = last_commit_map()
    files = []
    for dirpath, dirs, names in os.walk(KB):
        dirs.sort()
        for n in sorted(names):
            full = os.path.join(dirpath, n)
            rel = os.path.relpath(full, KB).replace(os.sep, "/")
            if rel == os.path.basename(MANIFEST):
                continue
            repo_rel = os.path.relpath(full, ROOT).replace(os.sep, "/")
            files.append({
                "path": rel,
                "kind": kind_of(rel),
                "bytes": len(read_normalised(full)),
                "sha256": sha256(full),
                "declares": declared_source(full),
                "last_commit": commits.get(repo_rel, ""),
            })
    return files


def emit_yaml(files, status):
    lines = [
        "# Generated by sdlc/framework/tools/kb_manifest.py — do not edit by hand.",
        "generator_version: %s" % GENERATOR_VERSION,
        "generated_at: %s" % datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "repository_revision: %s" % (git("rev-parse", "--short", "HEAD") or "unknown"),
        "repository_branch: %s" % (git("rev-parse", "--abbrev-ref", "HEAD") or "unknown"),
        "# KB files not committed when this was generated (new or changed since repository_revision)",
        "uncommitted_files: %d" % uncommitted(),
        "validation_status: %s" % status,
        "file_count: %d" % len(files),
        "total_bytes: %d" % sum(f["bytes"] for f in files),
        "by_area:",
    ]
    areas = {}
    for f in files:
        area = f["path"].split("/")[0]
        areas.setdefault(area, [0, 0])
        areas[area][0] += 1
        areas[area][1] += f["bytes"]
    for a, (n, b) in sorted(areas.items()):
        lines.append("  %s: {files: %d, bytes: %d}" % (json.dumps(a), n, b))
    kinds = {}
    for f in files:
        kinds[f["kind"]] = kinds.get(f["kind"], 0) + 1
    lines.append("# kind: current = read when answering; archive, report, staging, pointer = do not answer from these")
    lines.append("by_kind:")
    for k, n in sorted(kinds.items()):
        lines.append("  %s: %d" % (k, n))
    lines.append("files:")
    for f in files:
        lines.append("  - path: %s" % json.dumps(f["path"]))
        lines.append("    kind: %s" % f["kind"])
        lines.append("    bytes: %d" % f["bytes"])
        lines.append("    sha256: %s" % f["sha256"])
        lines.append("    last_commit: %s" % json.dumps(f["last_commit"]))
        if f["declares"]:
            lines.append("    declares:")
            for k, v in sorted(f["declares"].items()):
                lines.append("      %s: %s" % (k, json.dumps(v)))
    return "\n".join(lines) + "\n"


def read_manifest():
    """Just the file entries; a minimal parser for the fixed shape emit_yaml writes."""
    if not os.path.exists(MANIFEST):
        return None, {}
    header, files, cur = {}, {}, None
    for line in open(MANIFEST, encoding="utf-8"):
        if line.startswith("  - path: "):
            cur = json.loads(line[len("  - path: "):])
            files[cur] = {}
        elif cur and line.startswith("    sha256: "):
            files[cur]["sha256"] = line.split(": ", 1)[1].strip()
        elif cur and line.startswith("    bytes: "):
            files[cur]["bytes"] = int(line.split(": ", 1)[1])
        elif not line.startswith(" ") and ": " in line and not line.startswith("#"):
            k, v = line.split(": ", 1)
            header[k] = v.strip()
    return header, files


def validate(as_json=False):
    header, recorded = read_manifest()
    if header is None:
        print("no manifest — run: kb_manifest.py generate")
        return 2
    now = {f["path"]: f for f in scan()}
    added = sorted(set(now) - set(recorded))
    removed = sorted(set(recorded) - set(now))
    changed = sorted(p for p in set(now) & set(recorded) if now[p]["sha256"] != recorded[p].get("sha256"))
    report = {"manifest_generated_at": header.get("generated_at"), "manifest_revision": header.get("repository_revision"),
              "added": added, "removed": removed, "changed": changed,
              "ok": not (added or removed or changed)}
    if as_json:
        print(json.dumps(report, indent=1))
    elif report["ok"]:
        print("knowledge base matches the manifest (%s files, generated %s at %s)" % (
            len(recorded), header.get("generated_at"), header.get("repository_revision")))
    else:
        print("knowledge base has drifted from the manifest (generated %s at %s):" % (
            header.get("generated_at"), header.get("repository_revision")))
        for label, items in (("added", added), ("removed", removed), ("changed", changed)):
            for p in items:
                print("  %-8s %s" % (label, p))
        print("run: kb_manifest.py generate  (in the same PR as the KB change)")
    return 0 if report["ok"] else 1


def main(argv):
    cmd = argv[1] if len(argv) > 1 else "validate"
    if cmd == "generate":
        files = scan()
        with open(MANIFEST, "w", encoding="utf-8") as f:
            f.write(emit_yaml(files, "generated"))
        print("wrote %s: %d files, %d bytes" % (os.path.relpath(MANIFEST, ROOT), len(files), sum(x["bytes"] for x in files)))
        return 0
    if cmd == "validate":
        return validate(as_json="--json" in argv)
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
