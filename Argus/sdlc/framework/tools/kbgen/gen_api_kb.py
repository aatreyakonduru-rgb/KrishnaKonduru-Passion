"""Render 10_ENDPOINT_REGISTRY.yaml and 11_API_DATA_CONTRACTS.yaml from the AST scan.

Usage: python3 extract_api.py > api.json && python3 gen_api_kb.py api.json
"""
import json
import os
import re
import sys
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
KB = REPO / "docs" / "knowledge-base"
# SDLC_KB_OUT: write into a staging copy of the KB (e.g. _REGEN/<date>) instead of the live one.
KB_OUT = Path(os.environ.get("SDLC_KB_OUT") or KB)

SRC = json.load(open(sys.argv[1] if len(sys.argv) > 1 else "api.json"))
KBDIR = str(KB_OUT / "MODULES/claims-web/api")
os.makedirs(KBDIR, exist_ok=True)
TODAY = date.today().isoformat()


def q(s):
    if s is None:
        return "null"
    s = str(s)
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def npath(p):
    p = (p or "/").strip()
    return p if p.startswith("/") else "/" + p


def describe(e):
    if e.get("docstring"):
        return e["docstring"][0]
    if e.get("summary"):
        return e["summary"].strip("'\"")
    words = re.sub(r"(?<!^)(?=[A-Z])", " ", e["handler"].replace("_api", "")).replace("_", " ")
    return words[0].upper() + words[1:].lower()


# ---------------------------------------------------------------- registry
total = sum(len(r["endpoints"]) for r in SRC["routers"])
ENDPOINTS = [e for r in SRC["routers"] for e in r["endpoints"]]
AUTH_SEEN = sorted({str(e["auth"]) for e in ENDPOINTS if e.get("auth")}) + \
    ["@%s()" % d for d in sorted({d for e in ENDPOINTS for d in e["decorators"]})]
NO_AUTH = sum(1 for e in ENDPOINTS if not (e.get("auth") or e["decorators"]))
lines = [
    "# Acme Claims API Endpoint Registry",
    "# Confidence: 1.0 — generated by AST scan of api/apps/*/api.py",
    "# Source repo: claims-web/api/",
    "# Base URL pattern: /{ACME_API_PATH}/api/{router_prefix}/{endpoint}",
    "# Default ACME_API_PATH: acme  ->  full URL: /acme/api/...",
    "# Paths are recorded exactly as declared in the @router decorator; a few are",
    "# declared without a leading slash, which Django Ninja still mounts under the prefix.",
    "",
    "metadata:",
    "  confidence: 1.0",
    f'  source: "api/apps/*/api.py — {len(SRC["routers"])} routers mounted in apps/app/api.py"',
    '  generation_method: "python ast scan (no runtime import)"',
    f'  generated: "{TODAY}"',
    '  base_url: "/{ACME_API_PATH}/api"',
    '  default_base_url: "/acme/api"',
    f"  total_endpoints: {total}",
    f"  auth_mechanism: {q(' + '.join(AUTH_SEEN) or 'none found by the scan')}",
    f"  endpoints_without_auth: {NO_AUTH}",
    "  auth_bypass_settings:",
    '    - "ENABLE_AUTH=false -> skips all auth"',
    '    - "TESTING=true -> skips @authenticate_request(strict=False) only"',
    "  not_mounted:",
]
for m in SRC["commented_out_mounts"]:
    lines.append(f'    - "{m} (import commented out in apps/app/api.py)"')
for m in SRC.get("declared_but_unmounted", []):
    lines.append(f'    - "{m} (router declared but never added to the route map — every path 404s)"')
odd = [r["prefix"] for r in SRC["routers"] if not str(r["prefix"]).startswith("/")]
if odd:
    lines.append("  mount_prefix_anomalies:")
    for o in odd:
        lines.append(f'    - "{o} — registered in root_path_route_map without a leading slash"')

lines += ["", "routers:"]
for r in SRC["routers"]:
    app = r["module"].replace("apps.", "").replace(".api", "")
    auth_req = any(e.get("auth") or e["decorators"] for e in r["endpoints"])
    lines += [
        f'  # {"-" * 68}',
        f"  - prefix: {q(npath(r['prefix']))}",
        f"    mount_literal: {q(r['prefix'])}",
        f"    app: {app}",
        f"    source_file: {r['file']}",
        f"    tags: {json.dumps(r['tags'])}",
        f"    auth_required: {str(auth_req).lower()}",
        "    endpoints:",
    ]
    for e in sorted(r["endpoints"], key=lambda x: (npath(x["path"]), x["method"])):
        decs = ", ".join(f"@{d}()" for d in e["decorators"]) or "none"
        lines += [
            f"      - path: {q(e['path'])}",
            f"        method: {e['method']}",
            f"        handler: {e['handler']}",
            f"        line: {e['line']}",
            f"        auth: {q(e.get('auth') or 'none')}",
            f"        auth_decorator: {q(decs)}",
        ]
        if e.get("response_model"):
            lines.append(f"        response_model: {q(e['response_model'])}")
        if e["params"]:
            lines.append("        params:")
            for p in e["params"]:
                lines.append(f"          - {{ name: {p['name']}, type: {q(p['annotation'])} }}")
        lines.append(f"        description: {q(describe(e))}")
    lines.append("")

open(f"{KBDIR}/10_ENDPOINT_REGISTRY.yaml", "w").write("\n".join(lines).rstrip("\n") + "\n")

# ---------------------------------------------------------- data contracts
by_file = {s["file"]: s for s in SRC["schemas"]}
clines = [
    "# Acme Claims API — Data Contracts",
    "# Module: api",
    "# Confidence: 1.0 — generated by AST scan of api/apps/**/schema.py and api.py",
    "# Each contract pairs an endpoint with the request models bound to its handler",
    "# parameters and the declared ninja `response=` model.",
    "# Schema field types are copied verbatim from the source annotations.",
    "",
    "metadata:",
    "  module: api",
    '  framework: "Django + Django Ninja"',
    "  pipeline_stage: 11",
    "  confidence: 1.0",
    f'  generated: "{TODAY}"',
    '  generation_method: "python ast scan (no runtime import)"',
    f"  total_endpoints: {total}",
    f"  total_schema_classes: {sum(len(s['classes']) for s in SRC['schemas'])}",
    "",
    "contracts:",
]
idx = 0
for r in SRC["routers"]:
    app = r["module"].replace("apps.", "").replace(".api", "")
    for e in sorted(r["endpoints"], key=lambda x: (npath(x["path"]), x["method"])):
        idx += 1
        clines += [
            f"  - endpoint_id: EP-{idx:03d}",
            f"    path: {q((npath(r['prefix']).rstrip('/') + npath(e['path'])) or '/')}",
            f"    method: {e['method']}",
            f"    app: {app}",
            f"    handler: {e['handler']}",
            f"    source: {q(r['file'] + ':' + str(e['line']))}",
        ]
        if e["params"]:
            clines.append("    request:")
            for p in e["params"]:
                clines.append(f"      - {{ name: {p['name']}, type: {q(p['annotation'])} }}")
        else:
            clines.append("    request: []")
        clines.append(f"    response_model: {q(e.get('response_model') or 'undeclared')}")
clines.append("")

clines.append("schemas:")
for s in SRC["schemas"]:
    app = s["file"].split("/")[2] if s["file"].startswith("api/apps/") else s["file"]
    clines += [f"  - file: {s['file']}", "    classes:"]
    for c in s["classes"]:
        clines += [
            f"      - name: {c['name']}",
            f"        bases: {json.dumps(c['bases'])}",
            f"        line: {c['line']}",
        ]
        if c["fields"]:
            clines.append("        fields:")
            for f in c["fields"]:
                clines.append(
                    f"          - {{ name: {f['name']}, type: {q(f['type'])}, required: {str(f['required']).lower()} }}"
                )
        else:
            clines.append("        fields: []")
open(f"{KBDIR}/11_API_DATA_CONTRACTS.yaml", "w").write("\n".join(clines).rstrip("\n") + "\n")
print("wrote registry + contracts")
