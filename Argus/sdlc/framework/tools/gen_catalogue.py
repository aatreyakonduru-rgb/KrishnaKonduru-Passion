#!/usr/bin/env python3
"""Generate CATALOGUE.md — the listing that /catalogue prints.

Reads the repository itself (skill frontmatter, agent YAML, playbook headers) so the
listing cannot drift from what is actually installed. Run from anywhere:

    python3 sdlc/framework/tools/gen_catalogue.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
SKILLS = os.path.join(ROOT, ".devin", "skills")
AGENTS = os.path.join(ROOT, ".devin", "agents")
PLAYBOOKS = os.path.join(ROOT, "sdlc", "framework", "playbooks")
OUT = os.path.join(ROOT, "sdlc", "framework", "CATALOGUE.md")

DOCS_ONLY = {"PLAYBOOK-GUIDE.md", "PB-VALIDATION-multi-environment.md"}

NOISE = re.compile(
    r"\b(Invoke with|Say|Or|Source agent)\b\s*[:\"].*$",
    re.IGNORECASE | re.DOTALL,
)


def frontmatter(path):
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    block = text[3:end]
    out, key = {}, None
    for line in block.splitlines():
        m = re.match(r"^([A-Za-z_-]+):\s*(.*)$", line)
        if m:
            key, val = m.group(1), m.group(2).strip()
            out[key] = val
        elif key and line.strip():
            out[key] = (out[key] + " " + line.strip()).strip()
    return out


def one_line(text, limit=170):
    text = NOISE.sub("", text or "").strip()
    text = re.sub(r"\s+", " ", text).lstrip(">|- ").strip()
    for sep in (". ", " — "):
        if sep in text:
            text = text.split(sep)[0]
            break
    text = text.rstrip(" .")
    return text[: limit - 1] + "…" if len(text) > limit else text


def collect_skills():
    rows = []
    for name in sorted(os.listdir(SKILLS)):
        path = os.path.join(SKILLS, name, "SKILL.md")
        if os.path.isfile(path):
            fm = frontmatter(path)
            rows.append((name, one_line(fm.get("description", ""))))
    return rows


def yaml_scalar(text, key):
    m = re.search(rf"^{key}:\s*(.*)$", text, re.MULTILINE)
    if not m:
        return ""
    val = m.group(1).strip()
    if val in (">", "|", ">-", "|-"):
        body = text[m.end():].splitlines()
        parts = []
        for line in body:
            if line.strip() and not line.startswith((" ", "\t")):
                break
            parts.append(line.strip())
        val = " ".join(p for p in parts if p)
    return val.strip("\"'")


def collect_agents():
    rows = []
    for dirpath, _dirs, files in os.walk(AGENTS):
        for fname in files:
            if not fname.endswith(".agent.yaml"):
                continue
            path = os.path.join(dirpath, fname)
            with open(path, encoding="utf-8") as fh:
                text = fh.read()
            skills = []
            if "allowed_skills:" in text:
                tail = text[text.index("allowed_skills:") + len("allowed_skills:"):]
                for line in tail.splitlines():
                    m = re.match(r"^\s+-\s*([a-z0-9-]+)", line)
                    if m:
                        skills.append(m.group(1))
                    elif line.strip() and not line.lstrip().startswith("#"):
                        break
            rows.append((
                fname[: -len(".agent.yaml")],
                yaml_scalar(text, "role") or yaml_scalar(text, "name"),
                one_line(yaml_scalar(text, "goal"), 120),
                ", ".join(f"`/{s}`" for s in skills[:6]) + (f" +{len(skills) - 6} more" if len(skills) > 6 else "") or "—",
                os.path.relpath(path, ROOT).replace(os.sep, "/"),
            ))
    return sorted(rows)


def fenced(text, heading):
    m = re.search(rf"^##\s*{heading}.*$", text, re.MULTILINE)
    if not m:
        return ""
    m2 = re.search(r"```\s*\n(.*?)```", text[m.end():], re.DOTALL)
    return re.sub(r"\s+", " ", m2.group(1)).strip() if m2 else ""


def collect_playbooks():
    rows = []
    for fname in sorted(os.listdir(PLAYBOOKS)):
        if not fname.endswith(".md") or fname in DOCS_ONLY:
            continue
        with open(os.path.join(PLAYBOOKS, fname), encoding="utf-8") as fh:
            text = fh.read()
        slug = fname[:-3].replace("PB-", "pb_", 1).replace("-", "_").lower()
        cli = re.search(r"\*\*CLI equivalent:\*\*\s*`?([^`\n]+)`?", text)
        rows.append((
            "!" + slug,
            fenced(text, "Title") or fname[:-3],
            one_line(fenced(text, "Description"), 170),
            (cli.group(1).strip() if cli else "—"),
        ))
    return rows


def main():
    skills, agents, playbooks = collect_skills(), collect_agents(), collect_playbooks()
    lines = [
        "# Argus — Catalogue",
        "",
        "Generated by `sdlc/framework/tools/gen_catalogue.py` — do not edit by hand.",
        "Printed by `/catalogue` (`skills` · `playbooks` · `agents`); `/help` prints the role-based menu instead.",
        "",
        "| Skills | Agents | Playbooks |",
        "|---|---|---|",
        f"| {len(skills)} | {len(agents)} | {len(playbooks)} |",
        "",
        "---",
        "",
        f"## Skills ({len(skills)})",
        "",
        "Slash commands available in any session with this repository checked out.",
        "",
        "| Command | What it does |",
        "|---|---|",
    ]
    lines += [f"| `/{n}` | {d} |" for n, d in skills]

    lines += [
        "",
        "---",
        "",
        f"## Playbooks ({len(playbooks)})",
        "",
        "Registered in Devin Cloud (Settings → Playbooks). Type the macro to start a session "
        "pre-loaded with the instructions; the CLI equivalent is the skill you can run in an "
        "existing session instead.",
        "",
        "| Macro | Playbook | What it does | Skill equivalent |",
        "|---|---|---|---|",
    ]
    lines += [f"| `{m}` | {t} | {d} | `{c}` |" for m, t, d, c in playbooks]
    lines += [
        "",
        "`PLAYBOOK-GUIDE.md` and `PB-VALIDATION-multi-environment.md` are documentation, not "
        "runnable playbooks.",
    ]

    lines += [
        "",
        "---",
        "",
        f"## Agents ({len(agents)})",
        "",
        "Role profiles the skills adopt. You do not invoke an agent directly — a skill loads one.",
        "",
        "| Agent | Role | Purpose | Skills it may use |",
        "|---|---|---|---|",
    ]
    lines += [f"| `{n}` | {r} | {g} | {s} |" for n, r, g, s, _p in agents]
    lines += ["", "Agents without a `.agent.yaml` carry their profile in `AGENT.md` only.", ""]

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(skills)} skills, "
          f"{len(playbooks)} playbooks, {len(agents)} agents")
    return 0


if __name__ == "__main__":
    sys.exit(main())
