-- ID: CATALOG-TABLES
SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, TABLE_TYPE, ROW_COUNT, COMMENT
FROM {{DB}}.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA <> 'INFORMATION_SCHEMA' {{SCHEMA_FILTER:TABLE_SCHEMA}}
ORDER BY TABLE_SCHEMA, TABLE_NAME;
-- ID: CATALOG-COLUMNS
SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME, ORDINAL_POSITION, DATA_TYPE, IS_NULLABLE, COMMENT
FROM {{DB}}.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA <> 'INFORMATION_SCHEMA' {{SCHEMA_FILTER:TABLE_SCHEMA}}
ORDER BY TABLE_SCHEMA, TABLE_NAME, ORDINAL_POSITION;
