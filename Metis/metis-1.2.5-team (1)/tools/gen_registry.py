#!/usr/bin/env python3
"""Table registry, per-environment catalogue snapshots and the drift report, from saved catalogue queries and schema files.

    python3 gen_registry.py <kb> [--settings <kb>/.metis/kb-profile.yaml]

Sources, nothing else:
- saved catalogue queries <kb>/_EVIDENCE/queries/CATALOG-<TABLES|COLUMNS|FKEYS>-<ENV>-<LABEL>.json with their .sql
  (planned by db_catalog.py; a set with no -<ENV>-<LABEL> belongs to the reference environment)
- schema files for databases with engine schema-files in .metis/db-environments.yaml (CREATE TABLE statements only)
Every database, schema and table is kept apart: a table is named <database>.<schema>.<table>.
Writes:
- <db_docs>/DB_TABLE_REGISTRY.yaml   every table and column of the reference environment, each with its source
- <db_docs>/catalog.links.yaml       table has column, column references column (declared foreign keys only)
- <db_docs>/environments/<env>/CATALOG_SNAPSHOT.yaml   tables and columns of each environment
- <db_docs>/DB_DRIFT.yaml            tables, columns and types that differ from the reference environment, both sources
"""
import argparse
import fnmatch
import json
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import db_catalog  # noqa: E402

HEAD = "# Generated by gen_registry.py from saved catalogue queries and schema files. Do not edit by hand.\n"
QFILE = re.compile(r"^CATALOG-(TABLES|COLUMNS|FKEYS)(?:-([A-Za-z0-9_]+?)-([A-Za-z0-9_]+))?\.json$")
CREATE = re.compile(r'(?i)^\s*create\s+(?:or\s+replace\s+)?(?:(?:global\s+|local\s+)?(?:temporary|temp|transient)\s+)?table\s+(?:if\s+not\s+exists\s+)?([A-Za-z0-9_."$\[\]`]+)')
COLUMN = re.compile(r'^\s*["`\[]?([A-Za-z_][A-Za-z0-9_$]*)["`\]]?\s+([A-Za-z][A-Za-z0-9_ ]*?(?:\s*\([0-9, ]*\))?)(?=\s|,|$)')
NOT_COL = re.compile(r"(?i)^\s*(constraint|primary\s+key|foreign\s+key|unique|check|index|key|exclude|like|period)\b")
REF = re.compile(r'(?i)\breferences\s+([A-Za-z0-9_."]+)\s*\(\s*"?([A-Za-z0-9_]+)"?\s*\)')


def load(p):
    if not os.path.isfile(p):
        return {}
    with open(p, encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


def rows_of(path):
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)
    return [{str(k).upper(): v for k, v in r.items()} for r in data]


def db_docs(kb, settings):
    p = (settings.get("paths") or {}).get("db_docs") or "db"
    p = p.replace("<KB>/", "").replace("<KB>", "")
    return os.path.join(kb, p) if not os.path.isabs(p) else p


def query_sets(kb, envs, ref):
    """{(env, label): {kind: (qid, rows)}} for every saved query that has both .sql and .json."""
    qdir = os.path.join(kb, "_EVIDENCE", "queries")
    names = {db_catalog.ident(e): e for e in envs}
    out = {}
    for f in sorted(os.listdir(qdir)) if os.path.isdir(qdir) else []:
        m = QFILE.match(f)
        if not m or not os.path.isfile(os.path.join(qdir, f[:-5] + ".sql")):
            continue
        kind, env, lab = m.group(1), m.group(2), m.group(3)
        env = names.get(env, env) if env else (ref or "default")
        out.setdefault((env, lab or ""), {})[kind] = (f[:-5], rows_of(os.path.join(qdir, f)))
    return out


def db_entry(envs, env, lab):
    for d in (envs.get(env) or {}).get("databases") or []:
        if db_catalog.label(d) == lab or (not lab and len(envs[env]["databases"]) == 1):
            return d
    return {}


def key_of(database, schema, table):
    return ".".join(str(x) for x in (database, schema, table) if x not in (None, ""))


def from_queries(env, lab, sets, d):
    tables = {}
    if "TABLES" not in sets or "COLUMNS" not in sets:
        return tables, []
    tq, trows = sets["TABLES"]
    cq, crows = sets["COLUMNS"]
    for r in trows:
        dbn = r.get("TABLE_CATALOG") or d.get("database")
        k = key_of(dbn, r.get("TABLE_SCHEMA"), r["TABLE_NAME"])
        e = {"key": k, "database": dbn, "schema": r.get("TABLE_SCHEMA"), "name": r["TABLE_NAME"], "type": r.get("TABLE_TYPE"),
             "env": env, "label": lab or db_catalog.label(d) if d else lab, "engine": d.get("engine"),
             "source": "[E: query:%s]" % tq, "columns": []}
        e = {x: v for x, v in e.items() if v not in (None, "")}
        e.setdefault("columns", [])
        if r.get("ROW_COUNT") is not None:
            e["row_count"] = r["ROW_COUNT"]
        if r.get("COMMENT"):
            e["comment"] = r["COMMENT"]
        tables[k] = e
    for r in sorted(crows, key=lambda r: (str(r.get("TABLE_SCHEMA")), str(r["TABLE_NAME"]), int(r.get("ORDINAL_POSITION") or 0))):
        k = key_of(r.get("TABLE_CATALOG") or d.get("database"), r.get("TABLE_SCHEMA"), r["TABLE_NAME"])
        if k not in tables:
            continue
        col = {"name": r["COLUMN_NAME"], "data_type": r.get("DATA_TYPE"), "nullable": r.get("IS_NULLABLE"),
               "source": "[E: query:%s]" % cq}
        if r.get("COMMENT"):
            col["comment"] = r["COMMENT"]
        tables[k]["columns"].append({x: v for x, v in col.items() if v is not None})
    fkeys = []
    if "FKEYS" in sets:
        fq, frows = sets["FKEYS"]
        for r in frows:
            a = key_of(r.get("FK_DATABASE_NAME") or d.get("database"), r.get("FK_SCHEMA_NAME"), r.get("FK_TABLE_NAME"))
            b = key_of(r.get("PK_DATABASE_NAME") or d.get("database"), r.get("PK_SCHEMA_NAME"), r.get("PK_TABLE_NAME"))
            if not (r.get("FK_TABLE_NAME") and r.get("FK_COLUMN_NAME") and r.get("PK_TABLE_NAME") and r.get("PK_COLUMN_NAME")):
                continue
            fkeys.append({"from": "%s.%s" % (a, r["FK_COLUMN_NAME"]), "to": "%s.%s" % (b, r["PK_COLUMN_NAME"]),
                          "source": "[E: query:%s]" % fq})
    return tables, fkeys


def from_schema_files(kb, settings, env, d):
    """CREATE TABLE statements in the repo files named by the database entry. Each table and column cites its line."""
    import detect_stack
    ws, repos = detect_stack.repo_map(kb, settings, False)
    repo = d.get("repo")
    if repo not in repos:
        return {}, []
    base = repos[repo] if os.path.isabs(repos[repo]) else os.path.join(ws, repos[repo])
    tables, fkeys = {}, []
    for dp, dirs, files in os.walk(base):
        dirs[:] = sorted(x for x in dirs if x != ".git")
        for f in sorted(files):
            rel = os.path.relpath(os.path.join(dp, f), base).replace(os.sep, "/")
            if not any(fnmatch.fnmatch(rel, g) for g in d.get("paths") or []):
                continue
            lines = open(os.path.join(dp, f), encoding="utf-8", errors="replace").read().splitlines()
            cur = None
            for n, line in enumerate(lines, 1):
                m = CREATE.match(line)
                if m:
                    parts = [p.strip('"`[]') for p in m.group(1).split(".")]
                    schema = parts[-2] if len(parts) >= 2 else None
                    k = key_of(d.get("database"), schema, parts[-1])
                    cur = {"key": k, "database": d.get("database"), "schema": schema, "name": parts[-1], "env": env,
                           "label": db_catalog.label(d), "engine": "schema-files",
                           "source": '[E: %s/%s:%d "%s"]' % (repo, rel, n, m.group(1)), "columns": []}
                    cur = {x: v for x, v in cur.items() if v not in (None, "")}
                    cur.setdefault("columns", [])
                    tables[k] = cur
                    rest = line[m.end():].lstrip(" (")
                    if not rest.strip():
                        continue
                    line = rest
                if cur is None:
                    continue
                if re.match(r"^\s*\)", line):
                    cur = None
                    continue
                if NOT_COL.match(line):
                    continue
                c = COLUMN.match(line)
                if not c:
                    continue
                col = {"name": c.group(1), "data_type": c.group(2).strip().upper(),
                       "source": '[E: %s/%s:%d "%s"]' % (repo, rel, n, c.group(1))}
                if re.search(r"(?i)\bnot\s+null\b|\bprimary\s+key\b", line):
                    col["nullable"] = "NO"
                cur["columns"].append(col)
                r = REF.search(line)
                if r:
                    tp = [p.strip('"') for p in r.group(1).split(".")]
                    to = key_of(d.get("database"), tp[-2] if len(tp) >= 2 else None, tp[-1])
                    fkeys.append({"from": "%s.%s" % (cur["key"], c.group(1)), "to": "%s.%s" % (to, r.group(2)),
                                  "source": '[E: %s/%s:%d "%s"]' % (repo, rel, n, r.group(0))})
                if line.rstrip().endswith(");"):
                    cur = None
    return tables, fkeys


def snapshots(kb, settings):
    envs, ref = db_catalog.environments(kb)
    snap = {}
    for (env, lab), sets in query_sets(kb, envs, ref).items():
        t, f = from_queries(env, lab, sets, db_entry(envs, env, lab))
        s = snap.setdefault(env, {"tables": {}, "foreign_keys": []})
        s["tables"].update(t)
        s["foreign_keys"] += f
    for env, e in envs.items():
        for d in e["databases"]:
            if d.get("engine") == "schema-files":
                t, f = from_schema_files(kb, settings, env, d)
                s = snap.setdefault(env, {"tables": {}, "foreign_keys": []})
                s["tables"].update(t)
                s["foreign_keys"] += f
    if not ref and len(snap) == 1:
        ref = next(iter(snap))
    return envs, ref, snap


def match_key(t):
    return ".".join(str(x) for x in (t.get("label") or t.get("database"), t.get("schema"), t["name"]) if x)


def drift(ref, snap):
    out = []
    if ref not in snap:
        return out
    base = {match_key(t): t for t in snap[ref]["tables"].values()}
    for env in sorted(snap):
        if env == ref:
            continue
        other = {match_key(t): t for t in snap[env]["tables"].values()}
        for k in sorted(set(base) | set(other)):
            a, b = base.get(k), other.get(k)
            if a and not b:
                out.append({"table": k, "change": "table only in %s" % ref, "env": env, "sources": [a["source"]]})
            elif b and not a:
                out.append({"table": k, "change": "table only in %s" % env, "env": env, "sources": [b["source"]]})
            else:
                ca, cb = {c["name"]: c for c in a["columns"]}, {c["name"]: c for c in b["columns"]}
                for c in sorted(set(ca) | set(cb)):
                    if c not in cb:
                        out.append({"table": k, "column": c, "change": "column only in %s" % ref, "env": env, "sources": [ca[c]["source"]]})
                    elif c not in ca:
                        out.append({"table": k, "column": c, "change": "column only in %s" % env, "env": env, "sources": [cb[c]["source"]]})
                    elif str(ca[c].get("data_type")) != str(cb[c].get("data_type")):
                        out.append({"table": k, "column": c, "change": "type %s in %s, %s in %s" % (
                            ca[c].get("data_type"), ref, cb[c].get("data_type"), env), "env": env,
                            "sources": [ca[c]["source"], cb[c]["source"]]})
    return out


def build(kb, settings):
    envs, ref, snap = snapshots(kb, settings)
    if not snap or ref not in snap:
        return None
    s = snap[ref]
    tables = s["tables"]
    links = []
    for key in sorted(tables):
        for col in tables[key]["columns"]:
            links.append({"from": {"type": "table", "name": key}, "rel": "has column",
                          "to": {"type": "column", "name": "%s.%s" % (key, col["name"])}, "source": col["source"]})
    for fk in s["foreign_keys"]:
        links.append({"from": {"type": "column", "name": fk["from"]}, "rel": "references",
                      "to": {"type": "column", "name": fk["to"]}, "source": fk["source"]})
    dbs = sorted({(t.get("label") or "", t.get("database") or "", t.get("engine") or "") for t in tables.values()})
    reg = {"reference_environment": ref,
           "databases": [{"label": a, "database": b, "engine": c,
                          "schemas": sorted({t.get("schema") for t in tables.values() if (t.get("database") or "") == b and t.get("schema")})}
                         for a, b, c in dbs],
           "tables": [tables[k] for k in sorted(tables)], "foreign_keys": s["foreign_keys"]}
    return reg, links, snap, drift(ref, snap), envs


def write(p, data):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8") as fh:
        fh.write(HEAD)
        yaml.safe_dump(data, fh, sort_keys=False, allow_unicode=True, width=120)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("kb")
    ap.add_argument("--settings")
    a = ap.parse_args(argv)
    settings = load(a.settings or os.path.join(a.kb, ".metis", "kb-profile.yaml"))
    res = build(a.kb, settings)
    if res is None:
        print("no catalogue queries or schema files for the reference environment; registry not built")
        return 0
    reg, links, snap, dr, envs = res
    out = db_docs(a.kb, settings)
    write(os.path.join(out, "DB_TABLE_REGISTRY.yaml"), reg)
    write(os.path.join(out, "catalog.links.yaml"), {"links": links})
    for env, s in snap.items():
        sub = ((envs.get(env) or {}).get("docs_dir") or os.path.join("environments", env)).strip("/")
        write(os.path.join(out, sub, "CATALOG_SNAPSHOT.yaml"),
              {"environment": env, "tables": [s["tables"][k] for k in sorted(s["tables"])], "foreign_keys": s["foreign_keys"]})
    write(os.path.join(out, "DB_DRIFT.yaml"), {"reference_environment": reg["reference_environment"],
                                               "environments": sorted(snap), "differences": dr})
    print("%d tables in %d databases (%s), %d environments, %d differences -> %s" % (
        len(reg["tables"]), len(reg["databases"]), reg["reference_environment"], len(snap), len(dr), out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
