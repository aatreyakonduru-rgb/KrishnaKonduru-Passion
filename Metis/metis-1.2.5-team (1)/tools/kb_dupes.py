#!/usr/bin/env python3
"""Find near-duplicate KB pages and paragraphs. Report only: nothing is merged, moved or deleted.

    python3 kb_dupes.py scan <kb> [--page-threshold 0.8] [--para-threshold 0.85] [--min-words 12] [--no-write]

Text is lower-cased with source tags, links and markup removed, cut into 5-word shingles, and each shingle is hashed (blake2b,
64 bits). Two things are compared:
  - Candidates are chosen cheaply so a large KB does not compare every pair: two texts are compared when they agree on any of
    four 16-bit slices of their SimHash, or share any of six MinHash values (the chance of sharing one is the overlap itself, so
    a pair at the 0.8 threshold is missed with probability under 0.1%; a pair just under it may or may not be compared).
  - Each candidate pair is then measured exactly with the Jaccard overlap of the two shingle sets. A pair is reported only when
    the overlap is at or above the threshold (pages 0.8, paragraphs 0.85 by default). The SimHash and MinHash only choose which pairs to
    measure; they never decide on their own. A pair whose text is identical after normalising is reported as `identical`.

Paragraphs are blocks between blank lines (a list item or table row counts as part of its block) of at least --min-words words;
only pairs on two different pages are reported. Generated pages and the folders the coverage report skips are not read.
Near-duplicate text is a maintenance risk (one copy gets fixed, the other does not); it is not wrong in itself. A lead decides.

The report is CROSS-LAYER/DUPLICATES.yaml. Quoted text in it has square brackets turned into round ones so the source check does
not read it as a claim. Pairs are limited per page so one boilerplate paragraph does not flood the report.
"""
import argparse
import datetime
import hashlib
import os
import re
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kb_coverage  # noqa: E402
import verify_kb  # noqa: E402

REPORT = "CROSS-LAYER/DUPLICATES.yaml"
HEAD = "# Generated by kb_dupes.py from the KB pages. Near-duplicate pages and paragraphs; nothing is deleted. Do not edit by hand.\n"
SHINGLE = 5
BANDS = 4
MINHASHES = 6
MIN_PAGE_WORDS = 30
MAX_PAIRS_PER_ITEM = 5
MAX_PARA_PAIRS = 200
LINK = re.compile(r"!?\[([^\]]*)\]\([^)]*\)")


def words(text):
    t = verify_kb.TAG.sub(" ", text)
    t = LINK.sub(r"\1", t)
    t = re.sub(r"<[^>]+>", " ", t)
    t = re.sub(r"[`*_#>|]", " ", t)
    return re.findall(r"[a-z0-9]+(?:[.'][a-z0-9]+)*", t.lower())


def shingles(ws, k=SHINGLE):
    if not ws:
        return set()
    if len(ws) < k:
        return {" ".join(ws)}
    return {" ".join(ws[i:i + k]) for i in range(len(ws) - k + 1)}


def h64(s):
    return int.from_bytes(hashlib.blake2b(s.encode("utf-8"), digest_size=8).digest(), "big")


def simhash(sh):
    """64-bit SimHash of a set of shingles."""
    acc = [0] * 64
    for s in sh:
        h = h64(s)
        for b in range(64):
            acc[b] += 1 if (h >> b) & 1 else -1
    out = 0
    for b in range(64):
        if acc[b] > 0:
            out |= 1 << b
    return out


def hamming(a, b):
    return bin(a ^ b).count("1")


def jaccard(a, b):
    if not a or not b:
        return 0.0
    return len(a & b) / len(a | b)


def band_keys(sig):
    w = 64 // BANDS
    return [(i, (sig >> (i * w)) & ((1 << w) - 1)) for i in range(BANDS)]


def candidates(items):
    """Index pairs (i, j), i < j, whose SimHash agrees on at least one band. Items with identical text always pair."""
    buckets, seen = {}, set()
    for i, it in enumerate(items):
        for key in band_keys(it["sig"]) + [("m", k, v) for k, v in enumerate(it["mins"])] + [("x", it["digest"])]:
            buckets.setdefault(key, []).append(i)
    for members in buckets.values():
        if len(members) > 60:  # a bucket this crowded is boilerplate; compare only the first ones to stay near-linear
            members = members[:60]
        for a in range(len(members)):
            for b in range(a + 1, len(members)):
                i, j = members[a], members[b]
                if i != j:
                    seen.add((min(i, j), max(i, j)))
    return sorted(seen)


def minhashes(sh):
    """The smallest salted shingle hash for each of MINHASHES salts: two sets share one with probability equal to their overlap."""
    return [min(h64("%d|%s" % (k, s)) for s in sh) for k in range(MINHASHES)] if sh else []


def make(text, ref):
    ws = words(text)
    sh = shingles(ws)
    return dict(ref, words=len(ws), sh=sh, sig=simhash(sh), mins=minhashes(sh), digest=hashlib.sha1(" ".join(ws).encode("utf-8")).hexdigest())


def paragraphs(text):
    """[(first line number, block text)] blocks between blank lines, outside code blocks, front matter and headings."""
    out, cur, start, in_code, in_front = [], [], 0, False, False

    def flush():
        nonlocal cur, start
        if cur:
            out.append((start, "\n".join(cur)))
        cur, start = [], 0

    for n, raw in enumerate(text.splitlines(), 1):
        s = raw.strip()
        if n == 1 and s == "---":
            in_front = True
            continue
        if in_front:
            in_front = s != "---"
            continue
        if s.startswith("```"):
            flush()
            in_code = not in_code
            continue
        if in_code:
            continue
        if not s or re.match(r"^\|?\s*:?-{3,}[\s|:-]*$", s) or verify_kb.HEADING.match(s):
            flush()
            continue
        if not cur:
            start = n
        cur.append(raw)
    flush()
    return out


def defang(t):
    return " ".join(str(t).replace("[", "(").replace("]", ")").split())


def snippet(text):
    t = defang(verify_kb.TAG.sub("", text))
    return t if len(t) <= 160 else t[:157].rsplit(" ", 1)[0] + "..."


def limit(pairs, key_fn, cap=MAX_PAIRS_PER_ITEM):
    """Keep the strongest pairs, at most `cap` for any one item."""
    used, out = {}, []
    for p in sorted(pairs, key=lambda p: (-p["similarity"], str(key_fn(p)))):
        keys = key_fn(p)
        if any(used.get(k, 0) >= cap for k in keys):
            continue
        for k in keys:
            used[k] = used.get(k, 0) + 1
        out.append(p)
    return out


def scan(pages, page_threshold=0.8, para_threshold=0.85, min_words=12):
    """{pages: [...], paragraphs: [...]} from {rel: text}. Pure: no files are read or written."""
    pitems = [make(t, {"page": rel}) for rel, t in sorted(pages.items())]
    pitems = [p for p in pitems if p["words"] >= MIN_PAGE_WORDS]
    ppairs = []
    for i, j in candidates(pitems):
        a, b = pitems[i], pitems[j]
        sim = jaccard(a["sh"], b["sh"])
        if sim >= page_threshold or a["digest"] == b["digest"]:
            ppairs.append({"a": a["page"], "b": b["page"], "similarity": round(sim, 3),
                           "kind": "identical" if a["digest"] == b["digest"] else "near",
                           "words": [a["words"], b["words"]]})
    paras = []
    for rel, text in sorted(pages.items()):
        for n, block in paragraphs(text):
            it = make(block, {"page": rel, "line": n})
            if it["words"] >= min_words:
                it["text"] = block
                paras.append(it)
    gpairs = []
    for i, j in candidates(paras):
        a, b = paras[i], paras[j]
        if a["page"] == b["page"]:
            continue
        sim = jaccard(a["sh"], b["sh"])
        if sim >= para_threshold or a["digest"] == b["digest"]:
            gpairs.append({"a": {"page": a["page"], "line": a["line"]}, "b": {"page": b["page"], "line": b["line"]},
                           "similarity": round(sim, 3), "kind": "identical" if a["digest"] == b["digest"] else "near",
                           "words": a["words"], "text": snippet(a["text"])})
    ppairs = limit(ppairs, lambda p: (p["a"], p["b"]))
    reported = {(min(p["a"], p["b"]), max(p["a"], p["b"])) for p in ppairs}
    # a paragraph pair inside two pages already reported as near-duplicates is noise: the page pair says it
    gpairs = [p for p in gpairs if (min(p["a"]["page"], p["b"]["page"]), max(p["a"]["page"], p["b"]["page"])) not in reported]
    gpairs = limit(gpairs, lambda p: ((p["a"]["page"], p["a"]["line"]), (p["b"]["page"], p["b"]["line"])))[:MAX_PARA_PAIRS]
    return {"pages": sorted(ppairs, key=lambda p: (-p["similarity"], p["a"], p["b"])),
            "paragraphs": sorted(gpairs, key=lambda p: (-p["similarity"], p["a"]["page"], p["a"]["line"], p["b"]["page"]))}


def build(kb, page_threshold=0.8, para_threshold=0.85, min_words=12):
    pages = kb_coverage.page_files(kb)
    found = scan(pages, page_threshold, para_threshold, min_words)
    return {"as_of": datetime.date.today().isoformat(),
            "method": "5-word shingles, SimHash to pick candidates, exact Jaccard overlap to decide; see the top of tools/kb_dupes.py",
            "note": "Near-duplicate text is a maintenance risk, not an error. Nothing is merged or deleted; a lead decides.",
            "thresholds": {"page": page_threshold, "paragraph": para_threshold, "min_paragraph_words": min_words},
            "pages_read": len(pages), "page_pairs": len(found["pages"]), "paragraph_pairs": len(found["paragraphs"]),
            "duplicate_pages": found["pages"], "duplicate_paragraphs": found["paragraphs"]}


def write_report(kb, rep):
    path = os.path.join(kb, *REPORT.split("/"))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEAD)
        yaml.safe_dump(rep, fh, sort_keys=False, allow_unicode=True, width=120)
    return path


def load_report(kb):
    p = os.path.join(kb, *REPORT.split("/"))
    if not os.path.isfile(p):
        return {}
    with open(p, encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("scan"); s.add_argument("kb")
    s.add_argument("--page-threshold", type=float, default=0.8); s.add_argument("--para-threshold", type=float, default=0.85)
    s.add_argument("--min-words", type=int, default=12); s.add_argument("--no-write", action="store_true")
    a = ap.parse_args(argv)
    for t in (a.page_threshold, a.para_threshold):
        if not 0 < t <= 1:
            print("error: thresholds are between 0 and 1", file=sys.stderr)
            return 2
    kb = os.path.abspath(a.kb)
    rep = build(kb, a.page_threshold, a.para_threshold, a.min_words)
    for p in rep["duplicate_pages"]:
        print("page %.2f %s: %s = %s" % (p["similarity"], p["kind"], p["a"], p["b"]))
    for p in rep["duplicate_paragraphs"]:
        print("paragraph %.2f %s: %s:%d = %s:%d" % (p["similarity"], p["kind"], p["a"]["page"], p["a"]["line"], p["b"]["page"], p["b"]["line"]))
    where = "not written" if a.no_write else write_report(kb, rep)
    print("dupes: %d near-duplicate page pairs, %d paragraph pairs in %d pages -> %s" % (
        rep["page_pairs"], rep["paragraph_pairs"], rep["pages_read"], where))
    return 0


if __name__ == "__main__":
    sys.exit(main())
