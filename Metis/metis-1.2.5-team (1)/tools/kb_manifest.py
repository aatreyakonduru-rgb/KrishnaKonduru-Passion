#!/usr/bin/env python3
"""Knowledge-base manifest: every file in the KB folder, what it is, and how much of it is sourced.

    python3 kb_manifest.py generate <kb>    write <kb>/KNOWLEDGE-MANIFEST.yaml
    python3 kb_manifest.py validate <kb>    exit 1 if files were added, removed or changed since then

Each entry: path, kind (top folder), bytes, sha256, source tags, open-question references, the generator
named in a "Generated by" first line, and the git commit that last touched the file (when in a git repo).
"""
import datetime
import hashlib
import os
import re
import subprocess
import sys

import yaml

SKIP = (".git", "Archive", "_REGEN", "_PENDING", "_FEEDBACK")
LOCAL = (".metis/gate.lock", ".metis/usage/", ".metis/graph.sqlite", ".metis/trend.jsonl", ".metis/judge/", ".metis/contradict/",
         ".metis/search.sqlite", ".metis/facts.sqlite", ".metis/shared.sqlite", ".metis/exports/",
         ".metis/notify_state.json", ".metis/refresh_plan.json", ".metis/chat/")  # per-machine and derived: not KB content
NAME = "KNOWLEDGE-MANIFEST.yaml"
TAG = re.compile(r"\[E:\s*[^\]]+\]")
QREF = re.compile(r"\[\?:\s*(Q-\d+)\]")
GEN = re.compile(r"Generated by ([\w.]+)")


def last_commits(kb):
    """{path relative to kb: "<short hash> <date>"} from one `git log` pass (newest commit that touched each file)."""
    try:
        r = subprocess.run(["git", "-C", kb, "log", "--relative", "--name-only", "--format=%x00%h %cs"],
                           capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=300)
    except (OSError, subprocess.SubprocessError):
        return {}
    if r.returncode != 0:
        return {}
    out = {}
    for block in r.stdout.split("\x00")[1:]:
        head, _, files = block.partition("\n")
        for name in files.splitlines():
            if name.strip():
                out.setdefault(name.strip().strip('"'), head.strip())
    return out

def collect(kb, git=True):
    out = []
    commits = last_commits(kb) if git else {}
    for dirpath, dirnames, filenames in os.walk(kb):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP)
        for name in sorted(filenames):
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, kb).replace(os.sep, "/")
            if rel == NAME or rel.startswith(LOCAL):
                continue
            with open(path, "rb") as fh:
                data = fh.read().replace(b"\r\n", b"\n")
            e = {"path": rel, "kind": rel.split("/")[0] if "/" in rel else "root", "bytes": len(data),
                 "sha256": hashlib.sha256(data).hexdigest()}
            if name.endswith((".md", ".yaml", ".yml")):
                text = data.decode("utf-8", "replace")
                e["source_tags"] = len(TAG.findall(text))
                qs = sorted(set(QREF.findall(text)))
                if qs:
                    e["open_questions"] = qs
                m = GEN.search(text.split("\n", 1)[0])
                if m:
                    e["generated_by"] = m.group(1)
            if rel in commits:
                e["last_commit"] = commits[rel]
            out.append(e)
    return out


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 2 or argv[0] not in ("generate", "validate"):
        print(__doc__)
        return 2
    cmd, kb = argv
    path = os.path.join(kb, NAME)
    if cmd == "generate":
        files = collect(kb)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("# Generated by kb_manifest.py. Do not edit by hand.\n")
            yaml.safe_dump({"as_of": datetime.date.today().isoformat(), "files": len(files), "entries": files},
                           fh, sort_keys=False, width=120)
        print("%d files -> %s" % (len(files), path))
        return 0
    if not os.path.isfile(path):
        print("no manifest; run generate")
        return 1
    with open(path, encoding="utf-8") as fh:
        old = {e["path"]: e["sha256"] for e in (yaml.safe_load(fh) or {}).get("entries") or []}
    new = {e["path"]: e["sha256"] for e in collect(kb, git=False)}
    added, removed = sorted(set(new) - set(old)), sorted(set(old) - set(new))
    changed = sorted(p for p in set(new) & set(old) if new[p] != old[p])
    for label, lst in (("added", added), ("removed", removed), ("changed", changed)):
        for p in lst:
            print("%s: %s" % (label, p))
    return 1 if added or removed or changed else 0


if __name__ == "__main__":
    sys.exit(main())
