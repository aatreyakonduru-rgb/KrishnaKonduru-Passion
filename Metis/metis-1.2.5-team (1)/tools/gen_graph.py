#!/usr/bin/env python3
"""Build the Metis ontology and link graph from source-backed links only.

    python3 gen_graph.py <kb> [--out <kb>/CROSS-LAYER]

Pipeline steps write links to `*.links.yaml` files anywhere in the KB:

    links:
      - from: {type: endpoint, name: "GET /orders"}
        rel: reads
        to: {type: table, name: ORDERS}
        source: "[E: api/src/OrderRepository.java:22 \"FROM ORDERS\"]"

Every link must carry a source tag that `verify_kb.py` resolves; a link without one, or whose source
does not resolve, is left out and listed under `rejected`. Nothing is added from names alone.
Every edge gets an `origin`, set from the file's name: `parsed` (CROSS-LAYER/parsed.links.yaml, from sql_links.py),
`catalogue` (catalog.links.yaml, from gen_registry.py), else `ai-proposed`. A single link may say `origin: ai-proposed` to lower
itself inside a parser's file; no link can raise its own origin: any other value in a link is ignored.
Writes ONTOLOGY.yaml (node types and relation types with counts), LINK_GRAPH.yaml (nodes and edges)
(gen_visuals.py draws them in VISUALIZATION/).
"""
import argparse
import datetime
import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import verify_kb  # noqa: E402


def collect(kb):
    for dirpath, dirnames, filenames in os.walk(kb):
        dirnames[:] = [d for d in dirnames if d not in (".git", "Archive", "_EVIDENCE", "_PENDING", "_FEEDBACK")]
        for name in sorted(filenames):
            if name.endswith(".links.yaml"):
                path = os.path.join(dirpath, name)
                with open(path, encoding="utf-8") as fh:
                    data = yaml.safe_load(fh) or {}
                for i, link in enumerate(data.get("links") or []):
                    yield os.path.relpath(path, kb), i, link


ORIGINS = {"parsed.links.yaml": "parsed", "catalog.links.yaml": "catalogue"}


def origin_of(rel, link=None):
    """Where a link came from, decided by the file's name: a parser's file is `parsed`, the table registry's is `catalogue`,
    every other file was written by a person or proposed by a model, so it is `ai-proposed` (the KB cannot tell those two apart,
    and it must not call an unchecked link parsed). The one thing a link may say about itself is `origin: ai-proposed`, which
    lowers it; a link can never raise its own origin, so `origin: parsed` in a hand-written file changes nothing."""
    if isinstance(link, dict) and str(link.get("origin") or "").strip().lower() == "ai-proposed":
        return "ai-proposed"
    base = os.path.basename(rel)
    if base.startswith("parsed.") and base.endswith(".links.yaml"):
        return "parsed"
    return ORIGINS.get(base, "ai-proposed")


def node_key(n):
    return "%s:%s" % (n.get("type"), n.get("name"))


def build(kb):
    chk = verify_kb.Checker(kb)
    nodes, edges, rejected = {}, [], []
    for rel, i, link in collect(kb):
        where = "%s#%d" % (rel, i)
        f, t, r, src = link.get("from") or {}, link.get("to") or {}, link.get("rel"), link.get("source") or ""
        if not (f.get("type") and f.get("name") and t.get("type") and t.get("name") and r):
            rejected.append({"at": where, "reason": "link needs from, rel and to with type and name"})
            continue
        tags = verify_kb.TAG.findall(src)
        if not tags or any(k != "E" for k, _ in tags):
            rejected.append({"at": where, "reason": "link has no source tag (E:)"})
            continue
        reasons = [x for k, v in tags for part in v.split(";") for x in [chk.resolve(k, part)] if x]
        if reasons:
            rejected.append({"at": where, "reason": "; ".join(reasons)})
            continue
        for n in (f, t):
            nodes.setdefault(node_key(n), {"id": node_key(n), "type": n["type"], "name": n["name"]})
        edges.append({"from": node_key(f), "rel": r, "to": node_key(t), "source": src, "defined_in": rel,
                      "origin": origin_of(rel, link)})
    types, rels = {}, {}
    for n in nodes.values():
        types[n["type"]] = types.get(n["type"], 0) + 1
    for e in edges:
        k = "%s -%s-> %s" % (nodes[e["from"]]["type"], e["rel"], nodes[e["to"]]["type"])
        rels[k] = rels.get(k, 0) + 1
    return sorted(nodes.values(), key=lambda n: n["id"]), edges, rejected, types, rels


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("kb")
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    out = a.out or os.path.join(a.kb, "CROSS-LAYER")
    os.makedirs(out, exist_ok=True)
    nodes, edges, rejected, types, rels = build(a.kb)
    today = datetime.date.today().isoformat()
    head = "# Generated by gen_graph.py from *.links.yaml; every edge names its source. Do not edit by hand.\n"
    with open(os.path.join(out, "ONTOLOGY.yaml"), "w", encoding="utf-8") as fh:
        fh.write(head)
        yaml.safe_dump({"as_of": today, "node_types": types, "relations": rels}, fh, sort_keys=True)
    with open(os.path.join(out, "LINK_GRAPH.yaml"), "w", encoding="utf-8") as fh:
        fh.write(head)
        yaml.safe_dump({"as_of": today, "nodes": nodes, "edges": edges, "rejected": rejected}, fh,
                       sort_keys=False, allow_unicode=True, width=120)
    print("%d nodes, %d edges, %d rejected -> %s" % (len(nodes), len(edges), len(rejected), out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
