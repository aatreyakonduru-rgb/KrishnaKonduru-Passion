#!/usr/bin/env python3
"""Check the Markdown links between KB pages: links to missing files, anchors that do not exist, and pages nothing links to. Report only.

    python3 kb_links.py check <kb> [--no-write]

For every Markdown page in the KB (generated pages included; _EVIDENCE, _PENDING, _FEEDBACK, _QUESTIONS, _REGEN, Archive, .metis and
.git are not read) this reads inline links `[text](target)` and reference definitions `[id]: target`, outside code blocks and inline
code, and checks each one that stays inside the KB:
  - `missing-file`    the target file or folder does not exist (a leading `/` means the KB root; otherwise relative to the page)
  - `missing-anchor`  the target is a Markdown page and `#anchor` matches none of its headings (GitHub-style slugs, repeated
                      headings get -1, -2) and none of its `<a id="..."/name="...">` anchors; `#top` is always accepted
  - `outside-kb`      the path climbs out of the KB folder
Web links (http, https, mailto, tel, ftp) and `[E: ...]` source tags are not checked and not followed. Anchors on non-Markdown
files (for example `file.sql#L10`) are not checked.

Orphans: a hand-written page (not generated) that no other page links to and that no index page lists. An index page is one named
index, README or *_INDEX (any case), or one whose first heading is Index or Contents; "lists" means a link to it or its path
written in the index page's text. Index pages and root-level pages are entry points and are not reported as orphans. An orphan is a
page nobody will find by browsing; it may still be read by search.

The report is CROSS-LAYER/LINK_CHECK.yaml (written unless --no-write). Nothing is edited. Exit code 0 when no link is broken, 1 when
one is; orphans do not change the exit code.
"""
import argparse
import datetime
import os
import re
import sys
import urllib.parse

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import verify_kb  # noqa: E402

REPORT = "CROSS-LAYER/LINK_CHECK.yaml"
HEAD = "# Generated by kb_links.py from the KB pages. Broken links and orphan pages; nothing is edited. Do not edit by hand.\n"
SKIP = (".git", ".metis", "Archive", "_EVIDENCE", "_PENDING", "_FEEDBACK", "_QUESTIONS", "_REGEN")
EXTERNAL = re.compile(r"^(?:[a-z][a-z0-9+.-]*:|//)", re.I)
INLINE = re.compile(r"(?<!\\)\[((?:[^\[\]\\]|\\.|\[[^\]]*\])*)\]\(\s*(<[^>]*>|[^()\s]*(?:\([^()\s]*\)[^()\s]*)*)(?:\s+(?:\"[^\"]*\"|'[^']*'))?\s*\)")
REFDEF = re.compile(r"^\s{0,3}\[([^\]]+)\]:\s*(<[^>]*>|\S+)")
ANCHOR_TAG = re.compile(r"<a\s+[^>]*?(?:id|name)\s*=\s*[\"']([^\"']+)[\"']", re.I)
INDEX_NAME = re.compile(r"^(index|readme|.*_index)\.md$", re.I)


def defang(t):
    return " ".join(str(t).replace("[", "(").replace("]", ")").split())


def slug(heading):
    t = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", heading)
    t = re.sub(r"<[^>]+>", "", t)
    t = t.replace("`", "").replace("*", "").strip().lower()
    t = re.sub(r"[^\w\- ]", "", t, flags=re.U)
    return t.replace(" ", "-")


def anchors(text):
    """Set of anchors a page offers: heading slugs (GitHub style) and explicit <a id/name> anchors."""
    out, seen, in_code = {"top"}, {}, False
    for line in text.splitlines():
        if line.strip().startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            continue
        m = verify_kb.HEADING.match(line.strip())
        if m:
            base = slug(m.group(2).rstrip("# ").strip())
            n = seen.get(base, 0)
            seen[base] = n + 1
            out.add(base if n == 0 else "%s-%d" % (base, n))
        out.update(ANCHOR_TAG.findall(line))
    return out


def strip_code(line):
    return re.sub(r"`[^`]*`", lambda m: " " * len(m.group(0)), line)


def links(text):
    """[(line number, link text, target)] outside code blocks and inline code."""
    out, in_code, in_front = [], False, False
    for n, raw in enumerate(text.splitlines(), 1):
        s = raw.strip()
        if n == 1 and s == "---":
            in_front = True
            continue
        if in_front:
            in_front = s != "---"
            continue
        if s.startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            continue
        line = strip_code(raw)
        m = REFDEF.match(line)
        if m:
            out.append((n, m.group(1), m.group(2)))
            continue
        for m in INLINE.finditer(line):
            out.append((n, m.group(1), m.group(2)))
    return out


def clean_target(t):
    t = t.strip()
    if t.startswith("<") and t.endswith(">"):
        t = t[1:-1].strip()
    return t


def markdown_files(kb):
    out = {}
    for dirpath, dirnames, filenames in os.walk(kb):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP)
        for name in sorted(filenames):
            if name.lower().endswith(".md"):
                rel = os.path.relpath(os.path.join(dirpath, name), kb).replace(os.sep, "/")
                with open(os.path.join(dirpath, name), encoding="utf-8", errors="replace") as fh:
                    out[rel] = fh.read()
    return out


def is_generated(text):
    return "Generated by" in text[:300]


def is_index(rel, text):
    if INDEX_NAME.match(os.path.basename(rel)):
        return True
    for line in text.splitlines():
        m = verify_kb.HEADING.match(line.strip())
        if m:
            return m.group(2).strip().lower().rstrip(":") in ("index", "contents", "table of contents")
    return False


def resolve(kb, rel, target):
    """(kind, detail, normalised KB-relative path or None) for a link target: kind is ok, external, skip, missing-file, outside-kb."""
    target = clean_target(target)
    if not target or EXTERNAL.match(target):
        return "external", "", None
    path, _, frag = target.partition("#")
    path = urllib.parse.unquote(path.split("?", 1)[0])
    if not path:
        return "ok", urllib.parse.unquote(frag), rel
    base = kb if path.startswith("/") else os.path.join(kb, os.path.dirname(rel))
    full = os.path.normpath(os.path.join(base, path.lstrip("/")))
    root = os.path.normpath(kb)
    if full != root and not full.startswith(root + os.sep):
        return "outside-kb", path, None
    if not os.path.exists(full):
        return "missing-file", path, None
    return "ok", urllib.parse.unquote(frag), os.path.relpath(full, kb).replace(os.sep, "/")


def check(kb):
    """{pages, links_checked, broken: [...], orphans: [...]} for the KB. Reads files only."""
    pages = markdown_files(kb)
    offered = {}
    broken, inbound, checked = [], {}, 0
    for rel, text in sorted(pages.items()):
        for n, label, target in links(text):
            kind, detail, dest = resolve(kb, rel, target)
            if kind == "external":
                continue
            checked += 1
            item = {"page": rel, "line": n, "text": defang(label)[:60], "target": defang(clean_target(target))}
            if kind in ("missing-file", "outside-kb"):
                broken.append(dict(item, problem=kind))
                continue
            if dest and dest != rel:
                inbound.setdefault(dest, set()).add(rel)
            if detail and dest in pages:
                if dest not in offered:
                    offered[dest] = anchors(pages[dest])
                if detail not in offered[dest] and detail.lower() not in {a.lower() for a in offered[dest]}:
                    broken.append(dict(item, problem="missing-anchor", anchor=defang(detail)))
    indexes = {r: t for r, t in pages.items() if is_index(r, t)}
    index_text = {r: t.replace("\\", "/") for r, t in indexes.items()}
    orphans = []
    for rel, text in sorted(pages.items()):
        if is_generated(text) or rel in indexes or "/" not in rel:
            continue
        if inbound.get(rel):
            continue
        if any(rel in t for r, t in index_text.items() if r != rel):
            continue
        orphans.append(rel)
    return {"as_of": datetime.date.today().isoformat(),
            "method": "Markdown links and anchors checked against the files in the KB; see the top of tools/kb_links.py",
            "pages": len(pages), "links_checked": checked, "broken_links": len(broken), "orphan_pages": len(orphans),
            "index_pages": sorted(indexes), "broken": broken, "orphans": orphans}


def write_report(kb, rep):
    path = os.path.join(kb, *REPORT.split("/"))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEAD)
        yaml.safe_dump(rep, fh, sort_keys=False, allow_unicode=True, width=120)
    return path


def load_report(kb):
    p = os.path.join(kb, *REPORT.split("/"))
    if not os.path.isfile(p):
        return {}
    with open(p, encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("check"); c.add_argument("kb"); c.add_argument("--no-write", action="store_true")
    a = ap.parse_args(argv)
    kb = os.path.abspath(a.kb)
    rep = check(kb)
    for b in rep["broken"]:
        print("%s:%d: %s: %s%s" % (b["page"], b["line"], b["problem"], b["target"], " (anchor %s)" % b["anchor"] if b.get("anchor") else ""))
    for o in rep["orphans"]:
        print("orphan: %s" % o)
    where = "not written" if a.no_write else write_report(kb, rep)
    print("links: %d links in %d pages, %d broken, %d orphan pages -> %s" % (rep["links_checked"], rep["pages"], rep["broken_links"],
                                                                            rep["orphan_pages"], where))
    return 1 if rep["broken_links"] else 0


if __name__ == "__main__":
    sys.exit(main())
