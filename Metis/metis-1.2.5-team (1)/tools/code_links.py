RE_TS_IMPORT = re.compile(r"""(?:import\s+(?:\{([^}]+)\}|([a-zA-Z0-9_]+)|\*\s+as\s+([a-zA-Z0-9_]+))\s+from\s+['"]([^'"]+)['"]|const\s+(?:\{([^}]+)\}|([a-zA-Z0-9_]+))\s*=\s*require\(['"]([^'"]+)['"]\))""", re.M)
RE_TS_CLASS = re.compile(r"(?:export\s+)?(?:default\s+)?(?:abstract\s+)?(class|interface)\s+([a-zA-Z0-9_]+)(?:\s*<[^>]+>)?(?:\s+extends\s+([a-zA-Z0-9_., <>]+))?(?:\s+implements\s+([a-zA-Z0-9_., <>]+))?", re.M)
RE_TS_NEST_CONTROLLER = re.compile(r"@Controller\s*\(\s*['\"]?([^'\")\s]*)['\"]?\s*\)", re.M)
RE_TS_NEST_METHOD = re.compile(r"@(Get|Post|Put|Delete|Patch)\s*\(\s*['\"]?([^'\")\s]*)['\"]?\s*\)", re.M)
RE_EXPRESS_ROUTE = re.compile(r"\b(?:app|router)\.(get|post|put|delete|patch)\s*\(\s*['\"]([^'\"]+)['\"]", re.M)
RE_FETCH_AXIOS = re.compile(r"\b(?:fetch\s*\(\s*['\"]([^'\"]+)['\"]|axios\.(get|post|put|delete|patch)\s*\(\s*['\"]([^'\"]+)['\"])", re.M)
RE_TYPEORM_ENTITY = re.compile(r"@(Entity|Table)\s*\(\s*['\"]([^'\"]+)['\"]", re.M)
RE_TS_DYNAMIC_EVAL = re.compile(r"\b(eval|Function)\s*\(", re.M)


def parse_ts_js(text, rel_path):
    lines = text.splitlines()
    links, symbols, unparsed = [], [], []

    def add_link(f_type, f_name, rel, t_type, t_name, line, cand):
        if not line or line > len(lines):
            return
        line_text = lines[line - 1]
        q = quote_for(cand, line_text)
        if not q:
            return
        links.append({
            "from": {"type": f_type, "name": f_name},
            "rel": rel,
            "to": {"type": t_type, "name": t_name},
            "line": line,
            "quote": q
        })

    module_name = os.path.splitext(os.path.basename(rel_path))[0]

    # Imports
    for m in RE_TS_IMPORT.finditer(text):
        imported_names = m.group(1) or m.group(2) or m.group(3) or m.group(5) or m.group(6)
        source_pkg = m.group(4) or m.group(7)
        line = text[:m.start()].count("\n") + 1
        if imported_names:
            for item in imported_names.split(","):
                name = item.strip().split(" as ")[0].strip()
                if name:
                    add_link("module", module_name, "imports", "class", name, line, name)
        elif source_pkg:
            add_link("module", module_name, "imports", "module", source_pkg, line, source_pkg)

    # Classes
    classes = []
    for m in RE_TS_CLASS.finditer(text):
        kind, name, extends, implements = m.group(1), m.group(2), m.group(3), m.group(4)
        line = text[:m.start()].count("\n") + 1
        symbols.append({"name": name, "kind": kind, "line": line})
        classes.append((name, line))
        if extends:
            for p in extends.split(","):
                p_name = p.strip().split("<")[0].strip()
                if p_name:
                    add_link("class", name, "references", "class", p_name, line, p_name)
        if implements:
            for i in implements.split(","):
                i_name = i.strip().split("<")[0].strip()
                if i_name:
                    add_link("class", name, "references", "class", i_name, line, i_name)

    primary_class = classes[0][0] if classes else module_name

    # NestJS Controller
    controller_prefix = ""
    for m in RE_TS_NEST_CONTROLLER.finditer(text):
        controller_prefix = clean_url(m.group(1) or "/")

    for m in RE_TS_NEST_METHOD.finditer(text):
        http_method = m.group(1).upper()
        p = m.group(2) or ""
        endpoint_path = clean_url(controller_prefix.rstrip("/") + "/" + p.lstrip("/"))
        endpoint_name = f"{http_method} {endpoint_path}"
        line = text[:m.start()].count("\n") + 1
        symbols.append({"name": endpoint_name, "kind": "endpoint", "line": line})
        add_link("class", primary_class, "exposes_endpoint", "endpoint", endpoint_name, line, m.group(1))
        add_link("endpoint", endpoint_name, "handled_by", "class", primary_class, line, m.group(1))

    # Express routes
    for m in RE_EXPRESS_ROUTE.finditer(text):
        http_method = m.group(1).upper()
        p = clean_url(m.group(2))
        endpoint_name = f"{http_method} {p}"
        line = text[:m.start()].count("\n") + 1
        symbols.append({"name": endpoint_name, "kind": "endpoint", "line": line})
        add_link("module", module_name, "exposes_endpoint", "endpoint", endpoint_name, line, m.group(1))
        add_link("endpoint", endpoint_name, "handled_by", "module", module_name, line, m.group(1))

    # Fetch / Axios HTTP calls
    for m in RE_FETCH_AXIOS.finditer(text):
        fetch_url = m.group(1)
        axios_method = (m.group(2) or "GET").upper()
        axios_url = m.group(3)
        url = clean_url(fetch_url or axios_url)
        http_method = axios_method if axios_url else "GET"
        endpoint_name = f"{http_method} {url}"
        line = text[:m.start()].count("\n") + 1
        add_link("module", module_name, "calls", "endpoint", endpoint_name, line, url.split("/")[-1] or url)

    # TypeORM Entity / Table
    for m in RE_TYPEORM_ENTITY.finditer(text):
        tbl = m.group(2)
        line = text[:m.start()].count("\n") + 1
        add_link("class", primary_class, "reads_table", "table", tbl, line, tbl)

    # Dynamic eval
    for m in RE_TS_DYNAMIC_EVAL.finditer(text):
        line = text[:m.start()].count("\n") + 1
        unparsed.append({"file": rel_path, "line": line, "reason": f"dynamic code execution: {m.group(1)}"})

    return links, symbols, unparsed


