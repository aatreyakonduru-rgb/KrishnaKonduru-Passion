def code_files(base):
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in sorted(filenames):
            ext = os.path.splitext(name)[1].lower()
            if ext in EXT_PYTHON or ext in EXT_JAVA or ext in EXT_TS_JS:
                yield os.path.join(dirpath, name)


def build(kb):
    chk = verify_kb.Checker(kb)
    ts_parsers = load_tree_sitter()
    seen_files = 0
    parsed_files = 0
    raw_links = []
    unparsed = []
    dropped = []

    for repo in sorted(chk.repos):
        base, err = chk.repo_path(repo + "/x")
        if err:
            continue
        base = os.path.dirname(base)
        if not os.path.isdir(base):
            continue
        for path in code_files(base):
            rel = "%s/%s" % (repo, os.path.relpath(path, base).replace(os.sep, "/"))
            seen_files += 1
            if os.path.getsize(path) > MAX_BYTES:
                unparsed.append({"file": rel, "reason": "file is over %d bytes" % MAX_BYTES})
                continue
            with open(path, encoding="utf-8", errors="replace") as fh:
                text = fh.read()
            ext = os.path.splitext(path)[1].lower()
            file_links, _, file_unp = [], [], []
            try:
                if ext in EXT_PYTHON:
                    file_links, _, file_unp = parse_python(text, rel)
                elif ext in EXT_JAVA:
                    file_links, _, file_unp = parse_java_any(text, rel, ts_parsers)
                elif ext in EXT_TS_JS:
                    file_links, _, file_unp = parse_ts_js(text, rel)
                parsed_files += 1
            except Exception as exc:
                file_unp.append({"file": rel, "reason": f"{type(exc).__name__}: {str(exc).splitlines()[0][:160]}"})

            unparsed.extend(file_unp)
            for lk in file_links:
                raw_links.append((rel, lk))

    links = []
    seen_edges = set()
    for rel, lk in raw_links:
        edge_key = (lk["from"]["type"], lk["from"]["name"], lk["rel"], lk["to"]["type"], lk["to"]["name"])
        if edge_key in seen_edges:
            continue
        line = lk["line"]
        q = lk["quote"]
        src = f'[E: {rel}:{line} "{q}"]'
        err = chk.resolve("E", src[4:-1])
        if err:
            dropped.append({"file": rel, "line": line, "edge": edge_key, "why": err})
            continue
        seen_edges.add(edge_key)
        links.append({
            "from": lk["from"],
            "rel": lk["rel"],
            "to": lk["to"],
            "source": src
        })

    return {
        "files": seen_files,
        "parsed": parsed_files,
        "links": links,
        "unparsed": unparsed,
        "dropped": dropped,
        "tree_sitter": sorted(ts_parsers.keys()) if ts_parsers else "none"
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("kb")
    ap.add_argument("--out")
    ap.add_argument("--merge-into-parsed", action="store_true", help="merge output into parsed.links.yaml")
    a = ap.parse_args(argv)

    out = a.out or (os.path.join(a.kb, "CROSS-LAYER", "parsed.links.yaml") if a.merge_into_parsed else os.path.join(a.kb, OUT))
    try:
        res = build(a.kb)
    except Exception as exc:
        print("cannot parse code: %s" % exc, file=sys.stderr)
        return 2

    if res["files"] == 0:
        if os.path.isfile(out) and not a.merge_into_parsed:
            os.remove(out)
        print("no code files in the source repos; no code links")
        return 0

    os.makedirs(os.path.dirname(out), exist_ok=True)

    if a.merge_into_parsed and os.path.isfile(out):
        with open(out, encoding="utf-8") as fh:
            existing = yaml.safe_load(fh) or {}
        existing_links = existing.get("links") or []
        existing_keys = {(l["from"]["type"], l["from"]["name"], l["rel"], l["to"]["type"], l["to"]["name"]) for l in existing_links}
        for lk in res["links"]:
            k = (lk["from"]["type"], lk["from"]["name"], lk["rel"], lk["to"]["type"], lk["to"]["name"])
            if k not in existing_keys:
                existing_links.append(lk)
                existing_keys.add(k)
        existing["links"] = existing_links
        with open(out, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(HEAD)
            yaml.safe_dump(existing, fh, sort_keys=False, allow_unicode=True, width=120)
        print("merged %d code links into %s" % (len(res["links"]), out))
        return 0

    data = {"as_of": datetime.date.today().isoformat()}
    data.update(res)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEAD)
        yaml.safe_dump(data, fh, sort_keys=False, allow_unicode=True, width=120)
    print("%d code files, %d parsed, %d links, %d unparsed, %d dropped -> %s"
          % (res["files"], res["parsed"], len(res["links"]), len(res["unparsed"]), len(res["dropped"]), out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
