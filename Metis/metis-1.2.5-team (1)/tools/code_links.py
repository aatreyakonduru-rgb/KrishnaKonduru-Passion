RE_JAVA_PKG = re.compile(r"^\s*package\s+([a-zA-Z0-9_.]+)\s*;", re.M)
RE_JAVA_IMPORT = re.compile(r"^[ \t]*import\s+(?:static\s+)?([a-zA-Z0-9_.]+)\s*;", re.M)
RE_JAVA_CLASS = re.compile(r"(?:public|protected|private|abstract|static|final|\s)*\b(class|interface|record|enum)\s+([a-zA-Z0-9_]+)(?:\s*<[^>]+>)?(?:\s+extends\s+((?:(?!\bimplements\b)[a-zA-Z0-9_., <>])+))?(?:\s*\bimplements\s+([a-zA-Z0-9_., <>]+))?", re.M)
RE_SPRING_HTTP_METHOD = re.compile(r"\bmethod\s*=\s*\{?\s*(?:RequestMethod\.)?(GET|POST|PUT|DELETE|PATCH)\b")
RE_JAVA_TABLE = re.compile(r'@Table\s*\(\s*name\s*=\s*["\']([^"\']+)["\']', re.M)
RE_JAVA_ENTITY = re.compile(r'@Entity(?:\s*\(\s*name\s*=\s*["\']([^"\']+)["\']\s*\))?', re.M)
RE_JAVA_REPO = re.compile(r'@Repository\b', re.M)
RE_JAVA_QUERY = re.compile(r'@Query\s*\(\s*(?:value\s*=\s*)?["\']([^"\']+)["\']', re.M)
RE_SPRING_REQ_MAP = re.compile(r'@RequestMapping\s*(?:\(\s*(?:(?:value|path)\s*=\s*)?\{?\s*["\']([^"\']*)["\'])?', re.M)
RE_SPRING_METHOD_MAP = re.compile(r'@(GetMapping|PostMapping|PutMapping|DeleteMapping|PatchMapping|RequestMapping)\s*(?:\(\s*(?:(?:value|path)\s*=\s*)?\{?\s*["\']([^"\']*)["\'])?', re.M)
RE_JAVA_METHOD = re.compile(r'(?:public|protected|private|static|final|\s)*\b([a-zA-Z0-9_<>\[\]]+)\s+([a-zA-Z0-9_]+)\s*\([^)]*\)\s*(?:throws\s+[a-zA-Z0-9_., ]+)?\s*\{', re.M)
RE_JAVA_JPA_REPO = re.compile(r'\b(?:extends|implements)\s+(?:JpaRepository|CrudRepository|PagingAndSortingRepository|ListCrudRepository|Repository)\s*<\s*([a-zA-Z0-9_]+)', re.M)
RE_JAVA_CALL = re.compile(r'\b([a-zA-Z_][a-zA-Z0-9_]*)\.([a-zA-Z_][a-zA-Z0-9_]*)\s*\(', re.M)
RE_JAVA_REFLECTION = re.compile(r'\b(Class\.forName|getMethod|getDeclaredMethod|newInstance|invoke)\b')


_JAVA_LEX = re.compile(r'"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\'|//[^\n]*|/\*.*?\*/', re.S)


def strip_java_comments(text):
    """Blank out // and /* */ comments with spaces (newlines and offsets are kept); string literals are left alone."""
    def blank(m):
        s = m.group(0)
        return re.sub(r"[^\n]", " ", s) if s.startswith(("//", "/*")) else s
    return _JAVA_LEX.sub(blank, text)


def split_type_list(s):
    """Split 'A<B, C>, D' on the commas that are not inside <>."""
    parts, depth, cur = [], 0, ""
    for ch in s:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return [p.strip() for p in parts if p.strip()]


def parse_java(text, rel_path):
    lines = text.splitlines()
    text = strip_java_comments(text)  # regexes must not see comments; line numbers stay the same
    links, symbols, unparsed = [], [], []

    def add_link(f_type, f_name, rel, t_type, t_name, line, cand):
        if not line or line > len(lines):
            return
        line_text = lines[line - 1]
        q = quote_for(cand, line_text)
        if not q:
            return
        links.append({
            "from": {"type": f_type, "name": f_name},
            "rel": rel,
            "to": {"type": t_type, "name": t_name},
            "line": line,
            "quote": q
        })

    # Package & Imports
    for m in RE_JAVA_IMPORT.finditer(text):
        target = m.group(1)
        line = text[:m.start()].count("\n") + 1
        short_name = target.rsplit(".", 1)[-1]
        add_link("module", os.path.splitext(os.path.basename(rel_path))[0], "imports", "class", short_name, line, short_name)

    # Class definitions
    classes = []
    for m in RE_JAVA_CLASS.finditer(text):
        kind, name, extends, implements = m.group(1), m.group(2), m.group(3), m.group(4)
        class_pos = text.find(kind + " " + name, m.start())
        line = text[:(class_pos if class_pos >= 0 else m.start())].count("\n") + 1
        symbols.append({"name": name, "kind": kind, "line": line})
        classes.append((name, line, m.start()))
        if extends:
            for parent in split_type_list(extends):
                p_name = parent.strip().split("<")[0].strip()
                if p_name and p_name not in ("Object", "Record"):
                    p_pos = text.find(p_name, m.start())
                    p_line = text[:p_pos].count("\n") + 1 if p_pos >= 0 else line
                    add_link("class", name, "references", "class", p_name, p_line, p_name)
        if implements:
            for iface in split_type_list(implements):
                i_name = iface.strip().split("<")[0].strip()
                if i_name and i_name not in ("Serializable", "Cloneable", "Comparable"):
                    i_pos = text.find(i_name, m.start())
                    i_line = text[:i_pos].count("\n") + 1 if i_pos >= 0 else line
                    add_link("class", name, "references", "class", i_name, i_line, i_name)

    primary_class = classes[0][0] if classes else os.path.splitext(os.path.basename(rel_path))[0]

    # Spring class-level @RequestMapping (only one that sits before the first type declaration)
    first_type_pos = min((c[2] for c in classes), default=len(text))
    class_prefix = ""
    for m in RE_SPRING_REQ_MAP.finditer(text):
        if m.start() < first_type_pos and m.group(1):
            class_prefix = clean_url(m.group(1))

    # Spring Method mappings
    spring_methods = {
        "GetMapping": "GET",
        "PostMapping": "POST",
        "PutMapping": "PUT",
        "DeleteMapping": "DELETE",
        "PatchMapping": "PATCH",
        "RequestMapping": "GET",
    }
    for m in RE_SPRING_METHOD_MAP.finditer(text):
        if m.start() < first_type_pos:
            continue  # class-level @RequestMapping is the prefix, not an endpoint
        ann_type = m.group(1)
        path_part = m.group(2) or ""
        http_method = spring_methods.get(ann_type, "GET")
        if ann_type == "RequestMapping":
            nxt = text.find("\n\n", m.end())
            hm = RE_SPRING_HTTP_METHOD.search(text[m.start():min(m.start() + 300, nxt if nxt > 0 else len(text))])
            if hm:
                http_method = hm.group(1)
        combined_path = clean_url(class_prefix.rstrip("/") + "/" + path_part.lstrip("/"))
        endpoint_name = f"{http_method} {combined_path}"
        line = text[:m.start()].count("\n") + 1
        symbols.append({"name": endpoint_name, "kind": "endpoint", "line": line})
        add_link("class", primary_class, "exposes_endpoint", "endpoint", endpoint_name, line, ann_type)
        add_link("endpoint", endpoint_name, "handled_by", "class", primary_class, line, ann_type)

    # JPA & Tables
    for m in RE_JAVA_TABLE.finditer(text):
        tbl = m.group(1)
        line = text[:m.start()].count("\n") + 1
        add_link("class", primary_class, "reads_table", "table", tbl, line, tbl)

    for m in RE_JAVA_ENTITY.finditer(text):
        tbl = m.group(1)
        line = text[:m.start()].count("\n") + 1
        if tbl:
            add_link("class", primary_class, "reads_table", "table", tbl, line, tbl)

    for m in RE_JAVA_JPA_REPO.finditer(text):
        entity = m.group(1)
        line = text[:m.start()].count("\n") + 1
        add_link("class", primary_class, "references", "class", entity, line, entity)

    for m in RE_JAVA_QUERY.finditer(text):
        sql = m.group(1)
        line = text[:m.start()].count("\n") + 1
        tables = re.findall(r"(?i)\b(?:from|join|into|update)\s+([a-zA-Z_][a-zA-Z0-9_.]*)", sql)
        for tbl in set(tables):
            if tbl.upper() not in ("SELECT", "WHERE", "SET", "VALUES", "GROUP", "ORDER", "TABLE"):
                is_write = bool(re.search(r"(?i)\b(insert|update|delete)\b", sql))
                rel = "writes_table" if is_write else "reads_table"
                add_link("class", primary_class, rel, "table", tbl, line, tbl if tbl in lines[line - 1] else "@Query")

    # Reflection checks
    for m in RE_JAVA_REFLECTION.finditer(text):
        line = text[:m.start()].count("\n") + 1
        unparsed.append({"file": rel_path, "line": line, "reason": f"reflection detected: {m.group(1)}"})

    return links, symbols, unparsed


