def symbols_for(path):
    """Return symbols for a source file at path:
    [{'name': str, 'kind': 'class'|'function'|'interface'|'endpoint', 'line': int, 'source': str}]
    """
    if not os.path.isfile(path):
        return []
    with open(path, encoding="utf-8", errors="replace") as fh:
        text = fh.read()
    ext = os.path.splitext(path)[1].lower()
    rel = os.path.basename(path)
    if ext in EXT_PYTHON:
        _, syms, _ = parse_python(text, rel)
    elif ext in EXT_JAVA:
        _, syms, _ = parse_java(text, rel)
    elif ext in EXT_TS_JS:
        _, syms, _ = parse_ts_js(text, rel)
    else:
        return []

    lines = text.splitlines()
    out = []
    for s in syms:
        line = s["line"]
        line_text = lines[line - 1] if 1 <= line <= len(lines) else ""
        q = quote_for(s["name"], line_text) or s["name"]
        out.append({
            "name": s["name"],
            "kind": s["kind"],
            "line": line,
            "source": f'[E: {rel}:{line} "{q}"]'
        })
    return out


