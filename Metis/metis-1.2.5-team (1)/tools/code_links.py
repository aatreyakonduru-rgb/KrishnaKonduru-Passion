class PythonExtractor(ast.NodeVisitor):
    def __init__(self, text, rel_path):
        self.text = text
        self.rel_path = rel_path
        self.lines = text.splitlines()
        self.links = []
        self.symbols = []
        self.unparsed = []
        self.module_name = os.path.splitext(os.path.basename(rel_path))[0]
        self.current_class = None
        self.current_func = None

    def add_link(self, from_type, from_name, rel, to_type, to_name, line, quote_cand):
        if not line or line > len(self.lines):
            return
        line_text = self.lines[line - 1]
        q = quote_for(quote_cand, line_text)
        if not q:
            return
        self.links.append({
            "from": {"type": from_type, "name": from_name},
            "rel": rel,
            "to": {"type": to_type, "name": to_name},
            "line": line,
            "quote": q
        })

    def visit_Import(self, node):
        for alias in node.names:
            self.add_link("module", self.module_name, "imports", "module", alias.name, node.lineno, alias.name)
        self.generic_visit(node)

    def visit_ImportFrom(self, node):
        mod = node.module or ""
        for alias in node.names:
            target = f"{mod}.{alias.name}" if mod else alias.name
            self.add_link("module", self.module_name, "imports", "module", target, node.lineno, alias.name)
        self.generic_visit(node)

    def visit_ClassDef(self, node):
        prev_class = self.current_class
        self.current_class = node.name
        self.symbols.append({"name": node.name, "kind": "class", "line": node.lineno})
        for base in node.bases:
            if isinstance(base, ast.Name):
                self.add_link("class", node.name, "references", "class", base.id, node.lineno, base.id)
            elif isinstance(base, ast.Attribute):
                self.add_link("class", node.name, "references", "class", base.attr, node.lineno, base.attr)
        # Check for __tablename__
        for item in node.body:
            if isinstance(item, ast.Assign):
                for target in item.targets:
                    if isinstance(target, ast.Name) and target.id == "__tablename__":
                        if isinstance(item.value, ast.Constant) and isinstance(item.value.value, str):
                            tbl = item.value.value
                            self.add_link("class", node.name, "reads_table", "table", tbl, item.lineno, tbl)
        self.generic_visit(node)
        self.current_class = prev_class

    def visit_FunctionDef(self, node):
        self._handle_func(node)

    def visit_AsyncFunctionDef(self, node):
        self._handle_func(node)

    def _handle_func(self, node):
        prev_func = self.current_func
        func_name = f"{self.current_class}.{node.name}" if self.current_class else node.name
        self.current_func = func_name
        self.symbols.append({"name": func_name, "kind": "function", "line": node.lineno})

        # Route decorators (Flask, FastAPI, Django)
        for dec in node.decorator_list:
            route_info = self._parse_route_decorator(dec)
            if route_info:
                http_method, path = route_info
                endpoint_name = f"{http_method} {path}"
                self.symbols.append({"name": endpoint_name, "kind": "endpoint", "line": dec.lineno})
                caller_type = "class" if self.current_class else "function"
                self.add_link(caller_type, func_name, "exposes_endpoint", "endpoint", endpoint_name, dec.lineno, path)
                self.add_link("endpoint", endpoint_name, "handled_by", caller_type, func_name, dec.lineno, path)

        self.generic_visit(node)
        self.current_func = prev_func

    def _parse_route_decorator(self, dec):
        if not isinstance(dec, ast.Call):
            return None
        func = dec.func
        attr_name = ""
        if isinstance(func, ast.Attribute):
            attr_name = func.attr.lower()
        elif isinstance(func, ast.Name):
            attr_name = func.id.lower()

        # e.g. @app.get('/path'), @router.post('/path')
        methods = {"get": "GET", "post": "POST", "put": "PUT", "delete": "DELETE", "patch": "PATCH"}
        if attr_name in methods:
            if dec.args and isinstance(dec.args[0], ast.Constant) and isinstance(dec.args[0].value, str):
                return methods[attr_name], clean_url(dec.args[0].value)

        # e.g. @app.route('/path', methods=['GET', 'POST'])
        if attr_name == "route":
            if dec.args and isinstance(dec.args[0], ast.Constant) and isinstance(dec.args[0].value, str):
                path = clean_url(dec.args[0].value)
                http_method = "GET"
                for kw in dec.keywords:
                    if kw.arg == "methods" and isinstance(kw.value, (ast.List, ast.Tuple)):
                        elts = [e.value for e in kw.value.elts if isinstance(e, ast.Constant)]
                        if elts:
                            http_method = str(elts[0]).upper()
                return http_method, path
        return None

    def visit_Call(self, node):
        caller = self.current_func or self.current_class or self.module_name
        caller_type = "function" if self.current_func else ("class" if self.current_class else "module")

        # Function calls
        callee_name = None
        if isinstance(node.func, ast.Name):
            callee_name = node.func.id
        elif isinstance(node.func, ast.Attribute):
            callee_name = node.func.attr

        # Dynamic dispatch / reflection detection
        if callee_name in ("getattr", "eval", "exec", "__import__", "import_module"):
            self.unparsed.append({
                "file": self.rel_path,
                "line": node.lineno,
                "reason": f"dynamic dispatch / reflection via {callee_name}"
            })

        # SQL execution detection e.g. cursor.execute("SELECT ... FROM tbl")
        if callee_name in ("execute", "executemany") and node.args:
            first_arg = node.args[0]
            if isinstance(first_arg, ast.Constant) and isinstance(first_arg.value, str):
                sql = first_arg.value
                tables = re.findall(r"(?i)\b(?:from|join|into|update)\s+([a-zA-Z_][a-zA-Z0-9_.]*)", sql)
                for tbl in set(tables):
                    if tbl.upper() not in ("SELECT", "WHERE", "SET", "VALUES", "GROUP", "ORDER", "TABLE"):
                        is_write = bool(re.search(r"(?i)\b(insert|update|delete|create|drop|alter)\b", sql))
                        rel = "writes_table" if is_write else "reads_table"
                        self.add_link(caller_type, caller, rel, "table", tbl, node.lineno, tbl)

        # Regular calls
        if callee_name and callee_name not in ("print", "len", "range", "str", "int", "float", "dict", "list", "set", "tuple", "isinstance"):
            self.add_link(caller_type, caller, "calls", "function", callee_name, node.lineno, callee_name)

        self.generic_visit(node)


def parse_python(text, rel_path):
    try:
        tree = ast.parse(text)
        extractor = PythonExtractor(text, rel_path)
        extractor.visit(tree)
        return extractor.links, extractor.symbols, extractor.unparsed
    except Exception as exc:
        return [], [], [{"file": rel_path, "reason": f"Python parse error: {exc}"}]


