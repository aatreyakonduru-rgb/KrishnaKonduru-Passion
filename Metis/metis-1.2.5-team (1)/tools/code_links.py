# Java extractor on a tree-sitter syntax tree (used when tree_sitter + tree_sitter_java import)
# ---------------------------------------------------------------------------

_JAVA_TYPE_DECLS = {"class_declaration": "class", "interface_declaration": "interface",
                    "record_declaration": "record", "enum_declaration": "enum"}
_SPRING_HTTP = {"GetMapping": "GET", "PostMapping": "POST", "PutMapping": "PUT", "DeleteMapping": "DELETE",
                "PatchMapping": "PATCH", "RequestMapping": "GET"}
_JPA_BASES = {"JpaRepository", "CrudRepository", "PagingAndSortingRepository", "ListCrudRepository", "Repository"}
_TYPE_NODES = ("type_identifier", "generic_type", "scoped_type_identifier")


def parse_java_ts(parser, text, rel_path):
    """Same output as parse_java, built from the tree-sitter syntax tree (no regex over source text)."""
    data = text.encode("utf-8")
    tree = parser.parse(data)
    lines = [ln.rstrip("\r") for ln in text.split("\n")]
    links, symbols, unparsed = [], [], []
    module = os.path.splitext(os.path.basename(rel_path))[0]

    def src(n):
        return data[n.start_byte:n.end_byte].decode("utf-8", "replace")

    def row(n):
        return n.start_point.row + 1

    def add_link(f_type, f_name, rel, t_type, t_name, line, cand):
        if not line or line > len(lines):
            return
        q = quote_for(cand, lines[line - 1])
        if q:
            links.append({"from": {"type": f_type, "name": f_name}, "rel": rel,
                          "to": {"type": t_type, "name": t_name}, "line": line, "quote": q})

    def type_name(n):
        if n.type == "generic_type":
            return type_name(n.children[0])
        if n.type == "scoped_type_identifier":
            return src(n.children[-1])
        return src(n)

    def supertypes(decl):
        for c in decl.children:
            if c.type == "superclass":
                for t in c.children:
                    if t.type in _TYPE_NODES:
                        yield "extends", t
            elif c.type in ("super_interfaces", "extends_interfaces"):
                clause = "implements" if c.type == "super_interfaces" else "extends"
                for tl in c.children:
                    if tl.type == "type_list":
                        for t in tl.children:
                            if t.type in _TYPE_NODES:
                                yield clause, t

    def annotations(decl):
        mods = next((c for c in decl.children if c.type == "modifiers"), None)
        return [c for c in mods.children if c.type in ("annotation", "marker_annotation")] if mods else []

    def ann_name(a):
        n = a.child_by_field_name("name")
        return src(n).rsplit(".", 1)[-1] if n else ""

    def literal(n):
        s = src(n)
        return s[3:-3].strip() if s.startswith('"""') else s[1:-1]

    def ann_values(a, keys):
        """String values of an annotation: positional value (only if 'value' is in keys) or key = value / key = {a, b}."""
        out = []
        args = a.child_by_field_name("arguments")
        if not args:
            return out

        def collect(v):
            if v.type == "string_literal":
                out.append(literal(v))
            elif v.type == "element_value_array_initializer":
                for c in v.children:
                    collect(c)
        for c in args.children:
            if c.type in ("string_literal", "element_value_array_initializer"):
                if "value" in keys:
                    collect(c)
            elif c.type == "element_value_pair":
                k, v = c.child_by_field_name("key"), c.child_by_field_name("value")
                if k is not None and v is not None and src(k) in keys:
                    collect(v)
        return out

    def request_method(a, default):
        args = a.child_by_field_name("arguments")
        for c in (args.children if args else []):
            if c.type == "element_value_pair":
                k, v = c.child_by_field_name("key"), c.child_by_field_name("value")
                if k is not None and v is not None and src(k) == "method":
                    if v.type == "element_value_array_initializer":
                        v = next((x for x in v.children if x.type not in ("{", "}", ",")), v)
                    word = src(v).rsplit(".", 1)[-1].upper()
                    if word in ("GET", "POST", "PUT", "DELETE", "PATCH"):
                        return word
        return default

    def add_query_tables(owner, a):
        for sql in ann_values(a, ("value",)):
            line = row(a)
            tables = re.findall(r"(?i)\b(?:from|join|into|update)\s+([a-zA-Z_][a-zA-Z0-9_.]*)", sql)
            for tbl in sorted(set(tables)):
                if tbl.upper() not in ("SELECT", "WHERE", "SET", "VALUES", "GROUP", "ORDER", "TABLE"):
                    rel = "writes_table" if re.search(r"(?i)\b(insert|update|delete)\b", sql) else "reads_table"
                    add_link("class", owner, rel, "table", tbl, line, tbl if tbl in lines[line - 1] else "@Query")

    def visit(node, owner, prefix):
        t = node.type
        if t in _JAVA_TYPE_DECLS:
            name_n = node.child_by_field_name("name")
            if name_n is not None:
                name = src(name_n)
                symbols.append({"name": name, "kind": _JAVA_TYPE_DECLS[t], "line": row(name_n)})
                for clause, tn in supertypes(node):
                    p = type_name(tn)
                    skip = ("Object", "Record") if clause == "extends" else ("Serializable", "Cloneable", "Comparable")
                    if p not in skip:
                        add_link("class", name, "references", "class", p, row(tn), p)
                    if tn.type == "generic_type" and p in _JPA_BASES:
                        targs = next((c for c in tn.children if c.type == "type_arguments"), None)
                        first = next((c for c in (targs.children if targs else []) if c.type in _TYPE_NODES), None)
                        if first is not None:
                            add_link("class", name, "references", "class", type_name(first), row(tn), type_name(first))
                prefix = ""
                for a in annotations(node):
                    an = ann_name(a)
                    if an == "RequestMapping":
                        vals = ann_values(a, ("value", "path"))
                        if vals:
                            prefix = clean_url(vals[0])
                    elif an in ("Table", "Entity"):
                        for tbl in ann_values(a, ("name",)):
                            add_link("class", name, "reads_table", "table", tbl, row(a), tbl)
                owner = name
        elif t == "method_declaration" and owner:
            for a in annotations(node):
                an = ann_name(a)
                if an in _SPRING_HTTP:
                    http = request_method(a, "GET") if an == "RequestMapping" else _SPRING_HTTP[an]
                    for p in (ann_values(a, ("value", "path")) or [""]):
                        ep = "%s %s" % (http, clean_url(prefix.rstrip("/") + "/" + p.lstrip("/")))
                        symbols.append({"name": ep, "kind": "endpoint", "line": row(a)})
                        add_link("class", owner, "exposes_endpoint", "endpoint", ep, row(a), an)
                        add_link("endpoint", ep, "handled_by", "class", owner, row(a), an)
                elif an == "Query":
                    add_query_tables(owner, a)
        elif t == "import_declaration":
            if not any(c.type == "asterisk" for c in node.children):
                sc = next((c for c in node.children if c.type in ("scoped_identifier", "identifier")), None)
                if sc is not None:
                    short = src(sc).rsplit(".", 1)[-1]
                    add_link("module", module, "imports", "class", short, row(node), short)
            return
        elif t == "method_invocation":
            nm = node.child_by_field_name("name")
            obj = node.child_by_field_name("object")
            if nm is not None:
                n = src(nm)
                if n == "forName" and obj is not None and src(obj) == "Class":
                    unparsed.append({"file": rel_path, "line": row(node), "reason": "reflection detected: Class.forName"})
                elif n in ("getMethod", "getDeclaredMethod", "newInstance", "invoke"):
                    unparsed.append({"file": rel_path, "line": row(node), "reason": "reflection detected: %s" % n})
        for c in node.children:
            visit(c, owner, prefix)

    visit(tree.root_node, None, "")
    return links, symbols, unparsed


def parse_java_any(text, rel_path, parsers=None):
    """tree-sitter when a Java parser is loaded and parses the file; otherwise the regex extractor."""
    if parsers and parsers.get("java") is not None:
        try:
            return parse_java_ts(parsers["java"], text, rel_path)
        except Exception:
            pass
    return parse_java(text, rel_path)


