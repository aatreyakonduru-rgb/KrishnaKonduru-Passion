def load_tree_sitter():
    """Load tree-sitter languages if installed."""
    try:
        import tree_sitter
    except ImportError:
        return {}
    parsers = {}
    # Python
    try:
        import tree_sitter_python
        lang = tree_sitter.Language(tree_sitter_python.language())
        parsers["python"] = tree_sitter.Parser(lang)
    except Exception:
        pass
    # Java
    try:
        import tree_sitter_java
        lang = tree_sitter.Language(tree_sitter_java.language())
        parsers["java"] = tree_sitter.Parser(lang)
    except Exception:
        pass
    # TypeScript
    try:
        import tree_sitter_typescript
        lang = tree_sitter.Language(tree_sitter_typescript.language_typescript())
        parsers["typescript"] = tree_sitter.Parser(lang)
    except Exception:
        pass
    # JavaScript
    try:
        import tree_sitter_javascript
        lang = tree_sitter.Language(tree_sitter_javascript.language())
        parsers["javascript"] = tree_sitter.Parser(lang)
    except Exception:
        pass
    return parsers


def quote_for(candidate, line_text):
    """Find a clean, safe quote string on line_text."""
    if not line_text:
        return None
    for cand in (candidate, candidate.rsplit(".", 1)[-1], candidate.rsplit(" ", 1)[-1]):
        if cand and '"' not in cand and "]" not in cand and cand in line_text:
            return cand
    cleaned = line_text.strip().replace('"', "'").replace("[", "(").replace("]", ")")
    if cleaned and len(cleaned) <= 60:
        return cleaned
    return None


def clean_url(path):
    if not path:
        return "/"
    p = path.strip().strip('"').strip("'")
    if not p.startswith("/"):
        p = "/" + p
    return p


