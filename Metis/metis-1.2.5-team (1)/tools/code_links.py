#!/usr/bin/env python3
"""Code dependency links: classes, endpoints, imports, calls, tables and references from Java, TypeScript/JavaScript and Python.

    python3 code_links.py <kb> [--out FILE] [--merge-into-parsed]

Reads source files in the repos named under sources.repos in <kb>/.metis/kb-profile.yaml (read only),
parses each with tree-sitter when available or pure-Python AST/regex fallbacks, and writes
<kb>/CROSS-LAYER/parsed.code.links.yaml (or merges into parsed.links.yaml).

Edge kinds:
  - imports: a module or class imports another module, class or package
  - calls: a function, controller, component or client calls another function, method or endpoint
  - exposes_endpoint: a controller or route handler exposes an HTTP endpoint
  - handled_by: an HTTP endpoint is handled by a controller or method
  - reads_table: an entity, repository, query or function reads a database table
  - writes_table: an entity, repository, query or function writes to a database table
  - references: a class extends, implements or references another class, interface or entity

Every link carries `[E: <repo>/<file>:<line> "<quote>"]` verified against verify_kb.
Unresolvable cases (reflection, dynamic dispatch, runtime-built URLs) go into `unparsed`.
"""
