#!/usr/bin/env python3
"""Column-level lineage: map target column -> source table.column through SELECT, CTEs, JOINs, aggregates, CASE.

    python3 column_lineage.py build  <kb> [--dialect snowflake] [--out FILE]
    python3 column_lineage.py impact <kb> <table.column> [--depth N] [--limit N]

Reads .sql files in source repos (including dbt models with ref/source), parses them with sqlglot,
and maps column-level dependencies to <kb>/CROSS-LAYER/column.links.yaml.
Supports catalogue-aware mode by expanding SELECT * when DB catalogue snapshots are present.

Every link carries `[E: <repo>/<file>:<line> "<quote>"]` verified against verify_kb.
Unresolvable cases (SELECT * without schema, dynamic SQL, stored procs) go into `unresolved`.
"""
import argparse
import datetime
import json
import os
import re
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sql_links  # noqa: E402
import verify_kb  # noqa: E402

OUT = os.path.join("CROSS-LAYER", "column.links.yaml")
SKIP_DIRS = {".git", "node_modules", "target", "build", "dist", "dbt_packages", ".venv", "venv", "__pycache__"}
MAX_BYTES = 2_000_000
HEAD = ("# Generated by column_lineage.py by parsing SQL column lineage with sqlglot. Do not edit by hand.\n"
        "# gen_graph.py marks every link in this file origin: parsed.\n")

CONFIG = re.compile(r"\{\{\s*config\s*\(.*?\)\s*\}\}", re.S)
BLOCK = re.compile(r"\{%.*?%\}|\{#.*?#\}", re.S)
REF = re.compile(r"""\{\{\s*ref\(\s*(?:['"][^'"]+['"]\s*,\s*)?['"]([^'"]+)['"]\s*(?:,[^)]*)?\)\s*\}\}""")
SOURCE = re.compile(r"""\{\{\s*source\(\s*['"]([^'"]+)['"]\s*,\s*['"]([^'"]+)['"]\s*\)\s*\}\}""")


def load_sqlglot():
    try:
        import sqlglot
        from sqlglot import exp
        from sqlglot.lineage import lineage
        from sqlglot.optimizer import qualify
    except ImportError:
        return None, None, None, None
    return sqlglot, exp, lineage, qualify


def load_catalogue_schema(kb):
    """Load table -> {column: type} from saved catalogue queries and registry files."""
    schema = {}
    ev_dir = os.path.join(kb, "_EVIDENCE", "queries")
    if os.path.isdir(ev_dir):
        for f in os.listdir(ev_dir):
            if f.startswith("CATALOG-COLUMNS") and f.endswith(".json"):
                p = os.path.join(ev_dir, f)
                try:
                    with open(p, encoding="utf-8") as fh:
                        rows = json.load(fh)
                    for r in rows:
                        t = str(r.get("TABLE_NAME") or r.get("table_name") or "")
                        c = str(r.get("COLUMN_NAME") or r.get("column_name") or "")
                        dtype = str(r.get("DATA_TYPE") or r.get("data_type") or "text")
                        if t and c:
                            schema.setdefault(t.lower(), {})[c.lower()] = dtype
                            s = str(r.get("TABLE_SCHEMA") or r.get("table_schema") or "")
                            if s:
                                schema.setdefault(f"{s.lower()}.{t.lower()}", {})[c.lower()] = dtype
                except Exception:
                    pass

    # Check DB_TABLE_REGISTRY.yaml
    for reg_path in (os.path.join(kb, "db", "DB_TABLE_REGISTRY.yaml"), os.path.join(kb, "DB_TABLE_REGISTRY.yaml")):
        if os.path.isfile(reg_path):
            try:
                with open(reg_path, encoding="utf-8") as fh:
                    data = yaml.safe_load(fh) or {}
                for t_entry in data.get("tables") or []:
                    t_name = t_entry.get("name") or t_entry.get("key") or ""
                    cols = {c["name"].lower(): c.get("data_type", "text") for c in t_entry.get("columns") or [] if c.get("name")}
                    if t_name and cols:
                        schema[t_name.lower()] = cols
                        if "." in t_name:
                            schema[t_name.rsplit(".", 1)[-1].lower()] = cols
            except Exception:
                pass
    return schema


def render_dbt(sql):
    """Render dbt Jinja into SQL while preserving column references in macros and line numbers."""
    def blank(m):
        return "\n" * m.group(0).count("\n")

    def keep(text):
        return lambda m: text(m) + "\n" * (m.group(0).count("\n"))

    def replace_macro(m):
        content = m.group(0)
        quoted = re.findall(r"['\"]([a-zA-Z_][a-zA-Z0-9_]*)['\"]", content)
        if quoted:
            cand = quoted[-1]
            if len(quoted) > 1 and cand.lower() in ("day", "month", "year", "hour", "minute", "second"):
                cand = quoted[0]
            return cand + "\n" * content.count("\n")
        return "__jinja__" + "\n" * content.count("\n")

    sql = CONFIG.sub(blank, sql)
    sql = BLOCK.sub(blank, sql)
    sql = REF.sub(keep(lambda m: m.group(1)), sql)
    sql = SOURCE.sub(keep(lambda m: "%s.%s" % m.groups()), sql)
    return re.sub(r"\{\{.*?\}\}", replace_macro, sql)


def quote_for(candidate, line_text):
    if not line_text:
        return None
    for cand in (candidate, candidate.rsplit(".", 1)[-1], candidate.rsplit(" ", 1)[-1]):
        if cand and '"' not in cand and "]" not in cand and cand in line_text:
            return cand
    cleaned = line_text.strip().replace('"', "'").replace("[", "(").replace("]", ")")
    if cleaned and len(cleaned) <= 60:
        return cleaned
    return None


def get_from_sources(exp, query):
    """Return {alias_lower: table_or_cte_name} for FROM and JOIN clauses."""
    sources = {}
    from_clause = query.args.get("from_") or query.args.get("from")
    if from_clause and from_clause.this:
        if isinstance(from_clause.this, exp.Table):
            t_name = sql_links.table_name(from_clause.this)
            alias = from_clause.this.alias.lower() if from_clause.this.alias else t_name.lower()
            sources[alias] = t_name
    for join in query.args.get("joins") or []:
        if join.this and isinstance(join.this, exp.Table):
            t_name = sql_links.table_name(join.this)
            alias = join.this.alias.lower() if join.this.alias else t_name.lower()
            sources[alias] = t_name
    return sources


def resolve_expr_columns(exp, sel, local_sources, cte_map, catalog_schema):
    """Recursively resolve columns inside a select expression back to base tables."""
    results = []
    for col_expr in sel.find_all(exp.Column):
        col_id = col_expr.name
        if not col_id or col_id == "*" or col_id == "__jinja__":
            continue
        tbl_alias = col_expr.table.lower() if col_expr.table else None
        target_sources = [local_sources[tbl_alias]] if tbl_alias and tbl_alias in local_sources else list(local_sources.values())
        for src_name in target_sources:
            if src_name.lower() in cte_map:
                up_cte = cte_map[src_name.lower()]
                up_sources = get_from_sources(exp, up_cte)
                matched = False
                if hasattr(up_cte, "selects"):
                    for up_sel in up_cte.selects:
                        if up_sel.alias_or_name.lower() == col_id.lower() and not isinstance(up_sel, exp.Star):
                            sub_res = resolve_expr_columns(exp, up_sel, up_sources, cte_map, catalog_schema)
                            results.extend(sub_res)
                            matched = True
                            break
                if not matched:
                    # Upstream CTE did select *
                    for us_alias, us_name in up_sources.items():
                        if us_name.lower() in cte_map:
                            sub_res = resolve_expr_columns(exp, col_expr, {us_alias: us_name}, cte_map, catalog_schema)
                            results.extend(sub_res)
                        else:
                            results.append((us_name, col_id))
            else:
                results.append((src_name, col_id))
    return results


def extract_column_lineage_for_stmt(sqlglot, exp, lineage_fn, qualify_fn, stmt, file_lines, schema=None):
    """Extract (target_col, source_table, source_col, line, quote_cand) tuples for a single statement."""
    schema = schema or {}
    results = []
    unresolved = []

    # Identify target table if CREATE / INSERT
    target_table = None
    target_kind = "table"
    target_cols = []

    if isinstance(stmt, exp.Insert):
        this_table = stmt.this.find(exp.Table) if stmt.this is not None else None
        if this_table and sql_links.is_real_table(exp, this_table):
            target_table = sql_links.table_name(this_table)
            if isinstance(stmt.this, exp.Schema):
                target_cols = [c.name for c in stmt.this.expressions if isinstance(c, exp.Identifier)]
    elif isinstance(stmt, exp.Create):
        this_table = stmt.this.find(exp.Table) if stmt.this is not None else None
        if this_table and sql_links.is_real_table(exp, this_table):
            target_table = sql_links.table_name(this_table)
            kind = str(stmt.args.get("kind") or "").upper()
            target_kind = "view" if kind == "VIEW" else "table"

    query = stmt.args.get("expression") if isinstance(stmt, (exp.Create, exp.Insert)) else stmt
    if not isinstance(query, (exp.Select, exp.Union)):
        query = stmt.find(exp.Select)

    if not query or not hasattr(query, "selects"):
        return target_table, target_kind, results, unresolved

    # Map CTE names
    cte_map = {}
    for cte in query.find_all(exp.CTE):
        if cte.alias:
            cte_map[cte.alias.lower()] = cte.this

    # Sources of the outer query
    query_sources = get_from_sources(exp, query)

    # Determine output columns
    output_columns = []
    for sel in query.selects:
        line = sel.meta.get("line") or 1
        if isinstance(sel, exp.Star):
            # If outer query selects * from a CTE
            for q_alias, q_name in query_sources.items():
                if q_name.lower() in cte_map:
                    last_cte = cte_map[q_name.lower()]
                    cte_sources = get_from_sources(exp, last_cte)
                    if hasattr(last_cte, "selects"):
                        for cte_sel in last_cte.selects:
                            if not isinstance(cte_sel, exp.Star):
                                c_name = cte_sel.alias_or_name
                                c_line = cte_sel.meta.get("line") or line
                                s_cols = resolve_expr_columns(exp, cte_sel, cte_sources, cte_map, schema)
                                output_columns.append((c_name, s_cols, c_line))
                elif q_name.lower() in schema:
                    for c_name in schema[q_name.lower()]:
                        output_columns.append((c_name, [(q_name, c_name)], line))
                else:
                    unresolved.append({"target": target_table, "reason": f"SELECT * on {q_name} without catalogue schema"})
            continue

        c_name = sel.alias_or_name
        if not c_name or c_name == "*":
            continue

        s_cols = resolve_expr_columns(exp, sel, query_sources, cte_map, schema)
        output_columns.append((c_name, s_cols, line))

    # Match target cols if explicit
    if target_cols and len(target_cols) == len(output_columns):
        output_columns = [(target_cols[i], s_cols, line) for i, (_, s_cols, line) in enumerate(output_columns)]

    for tgt_col, src_cols, line in output_columns:
        for src_tbl, src_col in src_cols:
            if src_tbl and src_col and src_col != "__jinja__":
                results.append((tgt_col, src_tbl, src_col, line, tgt_col))

    return target_table, target_kind, results, unresolved


def build(kb, dialect=None):
    sqlglot, exp, lineage_fn, qualify_fn = load_sqlglot()
    if sqlglot is None:
        raise RuntimeError("sqlglot is not installed (pip install sqlglot)")

    chk = verify_kb.Checker(kb)
    dialect = dialect or (chk.settings.get("parse") or {}).get("dialect") or (chk.settings.get("db") or {}).get("engine")
    try:
        sqlglot.Dialect.get_or_raise(dialect)
    except Exception:
        dialect = None

    import logging
    logging.getLogger("sqlglot").setLevel(logging.ERROR)

    catalog_schema = load_catalogue_schema(kb)
    seen_files = 0
    parsed_files = 0
    unparsed = []
    unresolved = []
    dropped = []
    raw_links = []

    for repo in sorted(chk.repos):
        base, err = chk.repo_path(repo + "/x")
        if err:
            continue
        base = os.path.dirname(base)
        if not os.path.isdir(base):
            continue
        for path in sql_links.sql_files(base):
            rel = "%s/%s" % (repo, os.path.relpath(path, base).replace(os.sep, "/"))
            seen_files += 1
            if os.path.getsize(path) > MAX_BYTES:
                unparsed.append({"file": rel, "reason": "file is over %d bytes" % MAX_BYTES})
                continue
            with open(path, encoding="utf-8", errors="replace") as fh:
                original = fh.read()
            lines = original.splitlines()
            dbt = "models" in rel.split("/")[:-1]
            stem = os.path.splitext(rel.rsplit("/", 1)[-1])[0]

            rendered = render_dbt(original)
            try:
                stmts = sqlglot.parse(rendered, read=dialect)
                parsed_files += 1
            except Exception as exc:
                unparsed.append({"file": rel, "reason": f"{type(exc).__name__}: {str(exc).splitlines()[0][:160]}"})
                continue

            for stmt in stmts:
                if stmt is None:
                    continue
                if isinstance(stmt, exp.Command):
                    unresolved.append({"file": rel, "reason": "bare command / stored procedure not parsed"})
                    continue
                try:
                    tgt_tbl, tgt_kind, col_lineage, stmt_unres = extract_column_lineage_for_stmt(
                        sqlglot, exp, lineage_fn, qualify_fn, stmt, lines, catalog_schema
                    )
                    target = tgt_tbl or (stem if dbt else None)
                    for un in stmt_unres:
                        unresolved.append(dict(un, file=rel))

                    if not target:
                        continue

                    for tgt_col, src_tbl, src_col, line, quote_cand in col_lineage:
                        raw_links.append((rel, target, tgt_col, src_tbl, src_col, line, quote_cand))
                except Exception as exc:
                    unparsed.append({"file": rel, "reason": f"lineage error: {exc}"})

    links = []
    seen = set()
    for rel, target_tbl, target_col, src_tbl, src_col, line, quote_cand in raw_links:
        from_name = f"{target_tbl}.{target_col}"
        to_name = f"{src_tbl}.{src_col}"
        if (from_name, to_name) in seen:
            continue
        lines = chk.lines(chk.repo_path(rel)[0])
        cand_line = line
        if cand_line > len(lines) or quote_cand not in lines[cand_line - 1]:
            found_line = None
            for scan in range(max(1, cand_line - 10), min(len(lines) + 1, cand_line + 20)):
                if quote_cand in lines[scan - 1]:
                    found_line = scan
                    break
            if found_line:
                cand_line = found_line
            else:
                # Search entire file for quote_cand
                for scan, l_text in enumerate(lines, 1):
                    if quote_cand in l_text:
                        cand_line = scan
                        break

        if not cand_line or cand_line > len(lines):
            dropped.append({"file": rel, "from": from_name, "to": to_name, "why": "no usable line number"})
            continue
        q = quote_for(quote_cand, lines[cand_line - 1])
        if not q:
            dropped.append({"file": rel, "line": cand_line, "from": from_name, "to": to_name, "why": "name not found on line"})
            continue
        src = f'[E: {rel}:{cand_line} "{q}"]'
        err = chk.resolve("E", src[4:-1])
        if err:
            dropped.append({"file": rel, "line": cand_line, "from": from_name, "to": to_name, "why": err})
            continue
        seen.add((from_name, to_name))
        links.append({
            "from": {"type": "column", "name": from_name},
            "rel": "derived from",
            "to": {"type": "column", "name": to_name},
            "source": src
        })

    return {
        "dialect": dialect or "sqlglot default",
        "sqlglot": sqlglot.__version__,
        "catalogue_tables": len(catalog_schema),
        "files": seen_files,
        "parsed": parsed_files,
        "links": links,
        "unparsed": unparsed,
        "unresolved": unresolved,
        "dropped": dropped
    }


def column_impact(kb, table, column=None, depth=None, limit=5000):
    """Walk downstream column lineage: which columns move when table.column changes.

    Returns: ([{'moves': col_name, 'depth': d, 'via': [step, ...]}], was_cut)
    """
    path = os.path.join(kb, OUT)
    if not os.path.isfile(path):
        build(kb)
    if not os.path.isfile(path):
        return [], False

    with open(path, encoding="utf-8") as fh:
        data = yaml.safe_load(fh) or {}

    links = data.get("links") or []
    moves_map = {}
    for l in links:
        f = l.get("from", {}).get("name")
        t = l.get("to", {}).get("name")
        src = l.get("source")
        if f and t:
            moves_map.setdefault(t.lower(), []).append({"from": f, "rel": l.get("rel", "derived from"), "to": t, "source": src})

    start_node = f"{table}.{column}".lower() if column else str(table).lower()
    matching_starts = [k for k in moves_map if k == start_node or k.endswith("." + start_node) or start_node.endswith("." + k)]
    if not matching_starts:
        matching_starts = [start_node]

    seen = set(matching_starts)
    out = []
    frontier = [(s, []) for s in matching_starts]
    level = 0
    cut = False

    while frontier and (depth is None or level < depth) and not cut:
        level += 1
        nxt = []
        for node, path_steps in frontier:
            for step in moves_map.get(node, []):
                other = step["from"].lower()
                if other in seen:
                    continue
                if len(out) >= limit:
                    cut = True
                    break
                seen.add(other)
                p = path_steps + [step]
                out.append({"moves": step["from"], "depth": level, "via": p})
                nxt.append((other, p))
            if cut:
                break
        frontier = nxt

    return out, cut


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd")

    # Build command
    b_parser = sub.add_parser("build")
    b_parser.add_argument("kb")
    b_parser.add_argument("--dialect")
    b_parser.add_argument("--out")

    # Impact command
    i_parser = sub.add_parser("impact")
    i_parser.add_argument("kb")
    i_parser.add_argument("target", help="table.column or table")
    i_parser.add_argument("column", nargs="?", default=None)
    i_parser.add_argument("--depth", type=int)
    i_parser.add_argument("--limit", type=int, default=5000)

    # Default to build if first arg is not a command
    if argv is None:
        argv = sys.argv[1:]
    if argv and argv[0] not in ("build", "impact", "-h", "--help"):
        argv = ["build"] + argv

    args = ap.parse_args(argv)

    if args.cmd == "impact":
        tbl = args.target
        col = args.column
        if not col and "." in tbl:
            tbl, col = tbl.split(".", 1)
        rows, cut = column_impact(args.kb, tbl, col, args.depth, args.limit)
        for r in rows:
            last = r["via"][-1]
            print(f"{r['depth']}\t{r['moves']}\t(derived from {last['to']})\t{last['source']}")
        print(f"{len(rows)} columns move" + ("; stopped at limit" if cut else ""))
        return 0

    # Build
    out = args.out or os.path.join(args.kb, OUT)
    try:
        res = build(args.kb, args.dialect)
    except RuntimeError as exc:
        print(f"cannot parse column lineage: {exc}", file=sys.stderr)
        return 2

    if res["files"] == 0:
        if os.path.isfile(out):
            os.remove(out)
        print("no .sql files in the source repos; no column lineage links")
        return 0

    os.makedirs(os.path.dirname(out), exist_ok=True)
    data = {"as_of": datetime.date.today().isoformat()}
    data.update(res)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEAD)
        yaml.safe_dump(data, fh, sort_keys=False, allow_unicode=True, width=120)
    print("%d SQL files, %d parsed, %d column links, %d unresolved, %d dropped -> %s"
          % (res["files"], res["parsed"], len(res["links"]), len(res["unresolved"]), len(res["dropped"]), out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
