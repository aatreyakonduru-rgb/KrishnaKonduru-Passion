#!/usr/bin/env python3
"""Find places where two KB pages say different things about the same thing. A build-time check; no model is called.

    python3 kb_contradict.py scan   <kb> [--batch NAME] [--min-confidence low|medium|high] [--raise --by NAME]
    python3 kb_contradict.py prompt <kb> [--batch NAME] [-o FILE]     a prompt for a Devin/Bob session to judge the candidate pairs
    python3 kb_contradict.py judged <kb> [FILE]                       read the judged answers and merge them into the report

How it works. Claims are read from hand-written KB pages (not generated ones, not Open questions / Sources / Change log sections)
by plain pattern matching: table rows (first cell is the entity, each column header is an attribute), `Schedule: nightly` lines
under an entity heading, `ORDERS_LOAD schedule: 02:00`, `X is owned by Y`, `X runs at / every ...`, `X has 12 columns`,
`X is a view`, `X uses Y`. A claim is (subject, attribute, value, page, line, the [E: ...] tags on the line). Subjects are
normalised (case, punctuation, articles); claims are grouped by (subject, attribute); two claims on DIFFERENT pages whose values
are not equal and not one inside the other (`nightly` and `nightly at 02:00` agree) are flagged as a pair.

What a flag is. Two lines that look as if they disagree. Many flags are not contradictions: the same name can mean two things, or
a value can differ by environment. Confidence is how reliable the pattern is: high for table cells and `key: value` lines and counts,
medium for owner, schedule, type and platform sentences, low for `X uses Y` and plain `X is Y`. A lead reads each pair; this tool
never edits a page. The report is CROSS-LAYER/CONTRADICTIONS.yaml (source tags in it are written without brackets so the source
check does not read them as claims).

--batch NAME checks the files staged in _PENDING/NAME against the live pages (a staged file replaces the live page of the same
path; a .DELETE marker removes it) and reports only pairs where one side is staged. Its report goes to
.metis/contradict/BATCH-NAME.yaml, not into the KB.

`--raise` (never the default) adds each open pair at or above --min-confidence (default medium) to the question register through
questions.py, for the role that owns the page's area. `prompt` writes .metis/contradict/PROMPT.md; the session writes
.metis/contradict/ANSWERS.yaml (judgements: id, verdict contradiction|compatible|unclear, reason, judged_by) and `judged` merges it:
a `compatible` pair is marked dismissed. The judgement is a reading of the two lines only; it does not say which one is right.
"""
import argparse
import datetime
import hashlib
import os
import re
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kb_coverage  # noqa: E402
import kb_gate  # noqa: E402
import questions  # noqa: E402
import verify_kb  # noqa: E402

REPORT = "CROSS-LAYER/CONTRADICTIONS.yaml"
WORK = os.path.join(".metis", "contradict")
HEAD = "# Generated by kb_contradict.py from the KB pages. Pairs of lines that look as if they disagree; a lead decides. Do not edit by hand.\n"
CONF = {"low": 0, "medium": 1, "high": 2}
VERDICTS = ("contradiction", "compatible", "unclear")
TAG = verify_kb.TAG
HEADING = verify_kb.HEADING
NEG = {"not", "no", "never", "without"}
EMPTY = {"", "-", "n/a", "na", "none", "tbd", "unknown", "?", "—", "–", "todo"}
SKIP_HEADS = {"", "#", "source", "sources", "evidence", "note", "notes", "description", "comment", "comments", "details",
              "tag", "tags", "reference", "references", "link", "links", "example", "examples", "e"}
KV_HEADS = {"attribute", "property", "key", "setting", "item", "field", "parameter", "metric", "fact"}
KV_VALUE = {"value", "details", "detail", "setting", "values"}
STOP_SUBJ = {"this", "that", "these", "those", "it", "they", "there", "which", "who", "what", "when", "if", "each", "every", "all",
             "some", "any", "no", "we", "you", "i", "he", "she", "here", "note", "see", "also", "however", "but", "and", "or"}
ATTR = {"schedule": "schedule", "frequency": "schedule", "cadence": "schedule", "cron": "schedule", "run schedule": "schedule",
        "owner": "owner", "owned by": "owner", "maintainer": "owner", "type": "type", "kind": "type", "count": "count",
        "retention": "retention", "timeout": "timeout", "port": "port", "version": "version", "sla": "sla", "size": "size",
        "platform": "platform", "language": "language", "runtime": "runtime", "host": "host", "server": "server",
        "database": "database", "schema": "schema", "status": "status", "environment": "environment"}
ATTR_RE = "|".join(re.escape(k) for k in sorted(ATTR, key=len, reverse=True))
DAY = r"(?:mon|tue|wed|thu|fri|sat|sun|week|the\s+\d|\d)"
OF = re.compile(r"^(?:the\s+)?(?P<k>%s)\s+(?:of|for)\s+(?P<s>.+?)\s+(?:is|are|was)\s+(?P<v>.+)$" % ATTR_RE, re.I)
KV_SUBJ = re.compile(r"^(?P<s>[^:=]+?)\s*(?:[-—–|,(]\s*|\s+)(?P<k>%s)\s*[:=]\s*(?P<v>\S.*)$" % ATTR_RE, re.I)
KV_HEAD = re.compile(r"^(?P<k>%s)\s*[:=]\s*(?P<v>\S.*)$" % ATTR_RE, re.I)
SENT = [
    ("owner", "medium", re.compile(r"^(?P<s>.+?)\s+(?:is |are )?(?:owned|maintained|managed|administered) by\s+(?P<v>.+)$", re.I)),
    ("count", "high", re.compile(r"^(?P<s>.+?)\s+(?:has|have|contains|holds|includes|consists of|comprises)\s+(?P<v>\d[\d,]*(?:\.\d+)?)\s+"
                                 r"(?P<u>[A-Za-z][A-Za-z_ ]*?)(?:\s+(?:in|per|for|and|that|which|of)\b.*)?$", re.I)),
    ("schedule", "medium", re.compile(r"^(?P<s>.+?)\s+(?:runs?|is scheduled|are scheduled|executes|starts|fires|is triggered|kicks off)\s+"
                                      r"(?P<v>(?:at|every|each|daily|nightly|weekly|hourly|monthly|once|twice|on\s+" + DAY + r"|on every)\b.*)$", re.I)),
    ("platform", "medium", re.compile(r"^(?P<s>.+?)\s+runs?\s+on\s+(?P<v>.+)$", re.I)),
    ("language", "medium", re.compile(r"^(?P<s>.+?)\s+(?:is written in|is implemented in|is built with)\s+(?P<v>.+)$", re.I)),
    ("uses", "low", re.compile(r"^(?P<s>.+?)\s+uses?\s+(?P<v>.+)$", re.I)),
    ("type", "medium", re.compile(r"^(?P<s>.+?)\s+(?:is|are)\s+(?:an?|the)\s+(?P<v>.+)$", re.I)),
    ("is", "low", re.compile(r"^(?P<s>.+?)\s+(?:is|are)\s+(?P<v>.+)$", re.I)),
]
SHORTEN = re.compile(r"\s*(?:,|;|\s[-—–]\s|\(|\bthat\b|\bwhich\b|\bwhere\b|\bwhen\b|\bbecause\b|\bso\b)\s*", re.I)
LINK = re.compile(r"!?\[([^\]]*)\]\([^)]*\)")


class ContradictError(ValueError):
    pass


# ---- reading claims ---------------------------------------------------------------------------
def plain(text):
    t = TAG.sub("", str(text))
    t = LINK.sub(r"\1", t)
    t = re.sub(r"<br\s*/?>", " ", t, flags=re.I)
    t = re.sub(r"<[^>]+>", "", t)
    t = t.replace("*", "").replace("`", "")
    return " ".join(t.split())


def defang(text):
    """Text safe to keep in a KB yaml file: no square brackets, so verify_kb does not read it as a tag."""
    return str(text).replace("[", "(").replace("]", ")")


def norm_subject(s):
    s = re.sub(r"\([^)]*\)", " ", str(s).lower())
    s = re.sub(r"'s\b", "", s)
    s = re.sub(r"[_\-\s]+", " ", s)
    s = re.sub(r"[^\w. /]", "", s).strip(" ./")
    return re.sub(r"^(the|a|an|this|our)\s+", "", s).strip()


def good_subject(ns):
    words = ns.split()
    return bool(words) and len(words) <= 6 and 2 <= len(ns) <= 60 and bool(re.search(r"[a-z]", ns)) and words[0] not in STOP_SUBJ


def norm_value(v):
    v = " ".join(plain(v).lower().split()).strip(" .;,:")
    v = re.sub(r"^(the|a|an)\s+", "", v)
    if re.fullmatch(r"[\d,]+(\.\d+)?", v):
        v = v.replace(",", "")
        v = re.sub(r"\.0+$", "", v)
    return v


def number(v):
    try:
        return float(v) if re.fullmatch(r"\d+(\.\d+)?", v) else None
    except ValueError:
        return None


def compatible(a, b):
    """True when two normalised values do not disagree: equal, or one's words are all inside the other's."""
    if a == b:
        return True
    na, nb = number(a), number(b)
    if na is not None and nb is not None:
        return na == nb
    ta, tb = set(re.findall(r"[\w:]+", a)), set(re.findall(r"[\w:]+", b))
    if not ta or not tb or (ta & NEG) != (tb & NEG):
        return False
    return ta <= tb or tb <= ta


def canon_attr(k):
    k = " ".join(str(k).lower().split())
    return ATTR.get(k, k)


def short(v):
    v = SHORTEN.split(plain(v), 1)[0].strip()
    return v if len(v.split()) <= 6 else ""


def make(rel, n, subj, attr, val, method, conf, tags, where, text):
    ns, nv = norm_subject(subj), norm_value(val)
    if not good_subject(ns) or nv in EMPTY or len(nv) > 80 or not attr:
        return None
    return {"page": rel, "line": n, "where": where, "subject": ns, "subject_raw": plain(subj)[:60], "attr": attr, "value": nv,
            "value_raw": plain(val)[:80], "method": method, "confidence": conf, "evidence": tags, "text": plain(text)[:240]}


def cells(s):
    return [c.strip() for c in re.split(r"(?<!\\)\|", s.strip().strip("|"))]


def sentence_claims(rel, n, line, heading, tags, where):
    body = re.sub(r"^\s*([-*+]|\d+[.)])\s+", "", line)
    t = plain(body)
    out = []
    for sent in re.split(r"(?<=[.!?])\s+(?=[A-Z\"(])", t):
        sent = sent.strip().rstrip(".!?").strip()
        if not sent:
            continue
        c = None
        m = OF.match(sent)
        if m:
            c = make(rel, n, m.group("s"), canon_attr(m.group("k")), m.group("v"), "attribute-of", "high", tags, where, t)
        if not c:
            m = KV_SUBJ.match(sent)
            if m:
                c = make(rel, n, m.group("s"), canon_attr(m.group("k")), m.group("v"), "key-value", "high", tags, where, t)
        if not c and heading:
            m = KV_HEAD.match(sent)
            if m:
                c = make(rel, n, heading, canon_attr(m.group("k")), m.group("v"), "heading-key-value", "high", tags, where, t)
        if not c:
            for attr, conf, rx in SENT:
                m = rx.match(sent)
                if not m:
                    continue
                v = m.group("v")
                if attr == "count":
                    unit = re.sub(r"ies$", "y", m.group("u").strip().lower())
                    unit = re.sub(r"(?<!s)s$", "", unit)
                    c = make(rel, n, m.group("s"), "count of " + unit, v, "sentence", conf, tags, where, t)
                else:
                    if attr in ("type", "is", "uses"):
                        v = short(v)
                    c = make(rel, n, m.group("s"), attr, v, "sentence", conf, tags, where, t)
                break
        if c:
            out.append(c)
    return out


def extract(rel, text, where="live"):
    """Claims from one page: [{page, line, where, subject, attr, value, method, confidence, evidence, text}]."""
    lines = text.splitlines()
    out, head, tbl, exempt, in_code, in_front, heading = [], None, None, False, False, False, ""
    for i, raw in enumerate(lines):
        n, s = i + 1, raw.strip()
        if n == 1 and s == "---":
            in_front = True
            continue
        if in_front:
            in_front = s != "---"
            continue
        if s.startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            continue
        h = HEADING.match(s)
        if h:
            heading = plain(h.group(2))
            exempt = bool(verify_kb.EXEMPT.search(h.group(2)))
            tbl = None
            continue
        if not s:
            tbl = None
            continue
        if exempt or s.startswith(("<!--", ">")):
            continue
        tags = [m.group(2).strip() for m in TAG.finditer(raw) if m.group(1) == "E"]
        if s.startswith("|"):
            if re.match(r"^\|?\s*:?-{3,}", s):
                continue
            row = cells(s)
            if tbl is None:
                nxt = lines[i + 1].strip() if i + 1 < len(lines) else ""
                if re.match(r"^\|?\s*:?-{3,}", nxt):
                    tbl = [canon_attr(plain(c)) if plain(c).lower() not in SKIP_HEADS else None for c in row]
                continue
            kv = len(tbl) >= 2 and tbl[0] is not None and tbl[0] in KV_HEADS and (tbl[1] or "") in KV_VALUE | {"value"}
            if kv and heading and len(row) >= 2:
                c = make(rel, n, heading, canon_attr(plain(row[0])), row[1], "table", "high", tags, where, s)
                if c:
                    out.append(c)
                continue
            if not row or not plain(row[0]):
                continue
            for j in range(1, min(len(row), len(tbl))):
                if tbl[j]:
                    c = make(rel, n, row[0], tbl[j], row[j], "table", "high", tags, where, s)
                    if c:
                        out.append(c)
            continue
        tbl = None
        out += sentence_claims(rel, n, raw, heading, tags, where)
    return out


def live_pages(kb, skip=()):
    return {rel: t for rel, t in kb_coverage.page_files(kb).items() if rel not in skip}


def staged_pages(kb, batch):
    """({rel: text} of the .md files staged in _PENDING/<batch>, {rel} of the live pages the batch removes)."""
    base = kb_gate.pending_dir(kb, batch)
    if not os.path.isdir(base):
        raise ContradictError("no staged batch %s" % batch)
    pages, removed = {}, set()
    for rel in kb_gate.pending_files(kb, batch):
        if rel.endswith(".DELETE"):
            removed.add(rel[:-len(".DELETE")])
        elif rel.endswith(".md"):
            text = kb_gate.read_text(os.path.join(base, rel))
            if "Generated by" not in text[:300]:
                pages[rel] = text
    return pages, removed


def claims_for(kb, batch=None):
    """(claims, number of pages read). With a batch: live pages the batch does not replace, plus the staged pages."""
    out, n = [], 0
    if batch:
        staged, removed = staged_pages(kb, batch)
        for rel, t in sorted(live_pages(kb, set(staged) | removed).items()):
            out += extract(rel, t)
            n += 1
        for rel, t in sorted(staged.items()):
            out += extract(rel, t, "staged:" + batch)
            n += 1
        return out, n
    for rel, t in sorted(live_pages(kb).items()):
        out += extract(rel, t)
        n += 1
    return out, n


# ---- pairs ------------------------------------------------------------------------------------
def side(c):
    return {"page": c["page"], "line": c["line"], "where": c["where"], "value": defang(c["value_raw"]),
            "evidence": [defang(e) for e in c["evidence"]], "text": defang(c["text"]), "method": c["method"]}


def find_pairs(claims, staged_only=False, per_key=10):
    groups = {}
    for c in claims:
        groups.setdefault((c["subject"], c["attr"]), []).append(c)
    out = []
    for key, cs in sorted(groups.items()):
        by_val = {}
        for c in cs:
            by_val.setdefault(c["value"], []).append(c)
        vals, found = sorted(by_val), 0
        for i in range(len(vals)):
            for j in range(i + 1, len(vals)):
                if found >= per_key or compatible(vals[i], vals[j]):
                    continue
                cand = [(a, b) for a in by_val[vals[i]] for b in by_val[vals[j]] if a["page"] != b["page"]]
                if staged_only:
                    cand = [p for p in cand if p[0]["where"] != "live" or p[1]["where"] != "live"]
                if not cand:
                    continue
                a, b = min(cand, key=lambda p: (min((p[0]["page"], p[0]["line"]), (p[1]["page"], p[1]["line"])),
                                               (p[0]["page"], p[0]["line"], p[1]["page"], p[1]["line"])))
                if (b["page"], b["line"]) < (a["page"], a["line"]):
                    a, b = b, a
                conf = min(a["confidence"], b["confidence"], key=lambda x: CONF[x])
                cid = "C-" + hashlib.sha1(("%s|%s|%s|%s" % (key[0], key[1], vals[i], vals[j])).encode("utf-8")).hexdigest()[:8]
                out.append({"id": cid, "subject": defang(a["subject_raw"] or key[0]), "attribute": key[1], "confidence": conf,
                            "status": "open", "a": side(a), "b": side(b),
                            "other_places": len(by_val[vals[i]]) + len(by_val[vals[j]]) - 2})
                found += 1
    out.sort(key=lambda e: (-CONF[e["confidence"]], e["subject"], e["attribute"], e["id"]))
    return out


def work_path(kb, name):
    return os.path.join(kb, WORK, name)


def load_judged(kb, path=None):
    """{claim pair id: judgement} from the answers file a Devin/Bob session wrote. Raises ContradictError on a bad file."""
    path = path or work_path(kb, "ANSWERS.yaml")
    if not os.path.isfile(path):
        return {}
    try:
        with open(path, encoding="utf-8") as fh:
            data = yaml.safe_load(fh) or {}
    except yaml.YAMLError as err:
        raise ContradictError("%s is not valid YAML: %s" % (path, err))
    items = data.get("judgements") if isinstance(data, dict) else data
    out = {}
    for j in items or []:
        if not isinstance(j, dict) or not str(j.get("id", "")).startswith("C-"):
            raise ContradictError("each judgement needs an id like C-1a2b3c4d")
        if j.get("verdict") not in VERDICTS:
            raise ContradictError("%s: verdict must be one of %s" % (j["id"], ", ".join(VERDICTS)))
        if not str(j.get("reason") or "").strip():
            raise ContradictError("%s: give the reason, from the two lines only" % j["id"])
        out[j["id"]] = {"verdict": j["verdict"], "reason": str(j["reason"]).strip(),
                        "judged_by": str(j.get("judged_by") or "unnamed session")}
    return out


def annotate(entries, judged):
    for e in entries:
        j = judged.get(e["id"])
        if j:
            e["judgement"] = j
            e["status"] = {"compatible": "dismissed", "contradiction": "confirmed", "unclear": "unclear"}[j["verdict"]]
    return entries


def build(kb, batch=None, min_confidence="low"):
    claims, pages = claims_for(kb, batch)
    entries = [e for e in find_pairs(claims, staged_only=bool(batch)) if CONF[e["confidence"]] >= CONF[min_confidence]]
    annotate(entries, load_judged(kb))
    return {"as_of": datetime.date.today().isoformat(),
            "scope": "staged batch %s against the live KB" % batch if batch else "live KB",
            "method": "pattern matching on hand-written KB pages; see the top of tools/kb_contradict.py",
            "note": "Each entry is two lines that look as if they disagree. Many are not contradictions. A lead decides; nothing is edited.",
            "pages_read": pages, "claims_read": len(claims), "pairs": len(entries), "contradictions": entries}


def write_report(kb, rep, batch=None):
    path = work_path(kb, "BATCH-%s.yaml" % kb_gate.slug(batch)) if batch else os.path.join(kb, *REPORT.split("/"))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEAD)
        yaml.safe_dump(rep, fh, sort_keys=False, allow_unicode=True, width=120)
    return path


def load_report(kb):
    p = os.path.join(kb, *REPORT.split("/"))
    if not os.path.isfile(p):
        return {}
    with open(p, encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


# ---- questions and the LLM-assist prompt -------------------------------------------------------
def kb_path(s):
    return s["page"] if s["where"] == "live" else "_PENDING/%s/%s" % (s["where"].split(":", 1)[1], s["page"])


def qtype(page):
    return {"db": "data", "etl": "etl-batch", "modules": "application", "app": "application"}.get(page.split("/")[0].lower(), "business")


def raise_entry(kb, e, by, priority="P2"):
    """Raise one pair as an open question through questions.py. Returns (question id, added)."""
    a, b = e["a"], e["b"]
    text = ('The KB pages disagree about the %s of %s: %s line %d says "%s", but %s line %d says "%s". '
            "Which is right, and what is the source?") % (e["attribute"], e["subject"], kb_path(a), a["line"], a["value"],
                                                          kb_path(b), b["line"], b["value"])
    context = ["[E: kb:%s:%d]" % (kb_path(s), s["line"]) for s in (a, b)]
    before = {q.get("id") for q in questions.load(questions.reg_path(kb)).get("questions") or []}
    qid, _ = questions.cmd_raise(kb, text, qtype(a["page"]), by, priority, sorted({a["page"], b["page"]}), context)
    return qid, qid not in before


def raise_open(kb, rep, by, min_confidence="medium"):
    """Raise every open or unclear pair at or above min_confidence. Returns [(pair id, question id, added)]."""
    out = []
    for e in rep.get("contradictions") or []:
        if e.get("status") in ("dismissed",) or CONF[e["confidence"]] < CONF[min_confidence]:
            continue
        qid, added = raise_entry(kb, e, by)
        out.append((e["id"], qid, added))
    return out


def raise_by_id(kb, cid, by):
    for e in load_report(kb).get("contradictions") or []:
        if e["id"] == cid:
            return raise_entry(kb, e, by)
    raise ContradictError("%s is not in %s" % (cid, REPORT))


def write_prompt(kb, rep, path=None):
    todo = [e for e in rep["contradictions"] if e.get("status") == "open"]
    lines = ["# Judge candidate contradictions in the KB", "",
             "Below are %d pairs of KB lines that look as if they disagree. For each pair, decide using ONLY the two lines shown:" % len(todo),
             "", "- `contradiction`: the two lines cannot both be true of the same thing.",
             "- `compatible`: both can be true (different context, environment, or one is more detailed).",
             "- `unclear`: the two lines do not say enough.", "",
             "Do not decide which line is right. Do not edit any page. Write your answers to `%s` as YAML:" % (WORK.replace(os.sep, "/") + "/ANSWERS.yaml"),
             "", "```yaml", "judgements:", "  - id: C-xxxxxxxx", "    verdict: contradiction", "    reason: one sentence, from the two lines only",
             "    judged_by: your name or session", "```", ""]
    for e in todo:
        a, b = e["a"], e["b"]
        lines += ["## %s (%s confidence)" % (e["id"], e["confidence"]), "Subject: %s. Attribute: %s." % (e["subject"], e["attribute"]),
                  "- A, %s line %d (%s): %s" % (kb_path(a), a["line"], a["where"], a["text"]),
                  "- B, %s line %d (%s): %s" % (kb_path(b), b["line"], b["where"], b["text"]), ""]
    path = path or work_path(kb, "PROMPT.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    return path, len(todo)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("scan"); s.add_argument("kb"); s.add_argument("--batch")
    s.add_argument("--min-confidence", default="low", choices=tuple(CONF)); s.add_argument("--raise", dest="raise_", action="store_true")
    s.add_argument("--by")
    p = sub.add_parser("prompt"); p.add_argument("kb"); p.add_argument("--batch"); p.add_argument("-o")
    j = sub.add_parser("judged"); j.add_argument("kb"); j.add_argument("file", nargs="?")
    a = ap.parse_args(argv)
    kb = os.path.abspath(a.kb)
    try:
        if a.cmd == "judged":
            got = load_judged(kb, a.file)
            if a.file:
                os.makedirs(os.path.join(kb, WORK), exist_ok=True)
                with open(work_path(kb, "ANSWERS.yaml"), "w", encoding="utf-8", newline="\n") as fh:
                    yaml.safe_dump({"judgements": [dict(id=k, **v) for k, v in sorted(got.items())]}, fh, sort_keys=False)
            rep = build(kb)
            write_report(kb, rep)
            print("%d judgements read; report updated (%d pairs)" % (len(got), rep["pairs"]))
            return 0
        rep = build(kb, a.batch, getattr(a, "min_confidence", "low"))
        if a.cmd == "prompt":
            path, n = write_prompt(kb, rep, a.o)
            print("wrote %s (%d pairs to judge)" % (path, n))
            return 0
        path = write_report(kb, rep, a.batch)
        for e in rep["contradictions"]:
            print("%s %-6s %s / %s: %s:%d '%s' vs %s:%d '%s'" % (e["id"], e["confidence"], e["subject"], e["attribute"],
                  kb_path(e["a"]), e["a"]["line"], e["a"]["value"], kb_path(e["b"]), e["b"]["line"], e["b"]["value"]))
        print("contradictions: %d pairs from %d claims on %d pages -> %s" % (rep["pairs"], rep["claims_read"], rep["pages_read"], path))
        if a.raise_:
            if not a.by:
                print("error: --raise needs --by NAME", file=sys.stderr)
                return 2
            for cid, qid, added in raise_open(kb, rep, a.by):
                print("%s -> %s%s" % (cid, qid, "" if added else " (already in the register)"))
    except (ContradictError, ValueError, kb_gate.GateError) as err:
        print("error: %s" % err, file=sys.stderr)
        return 2
    return 0


