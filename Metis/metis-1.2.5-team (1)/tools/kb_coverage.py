#!/usr/bin/env python3
"""Coverage report: what the KB does not know.

    python3 kb_coverage.py <kb>

Reads CROSS-LAYER/LINK_GRAPH.yaml, the table registry (if built) and the question register, and writes
CROSS-LAYER/COVERAGE.yaml with:
  - objects in the link graph that no hand-written KB page names (per type)
  - catalogue tables that no KB page names
  - links rejected by gen_graph.py, with the reasons
  - relation names and node types the impact matrix cannot use (see gen_matrix.py)
  - edges by origin (parsed, catalogue, ai-proposed), and the SQL files sql_links.py could not read or read only in part
  - open questions by priority, and the KB files they block

"Named" means the object's full name, or for a dotted name its last part as a whole word, appears in a Markdown
page that is not generated (no "Generated by" first line) and is not under CROSS-LAYER, VISUALIZATION, _EVIDENCE,
_QUESTIONS, _REGEN, _PENDING, _FEEDBACK, Archive or .metis. It is a name match, not a check that the page is right.
Not covered because 1.2.5 has no way to know: objects with no owner (the graph has no owner field), and SQL kept in
non-.sql files (strings in code, notebooks).
"""
import argparse
import datetime
import os
import re
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_matrix  # noqa: E402

SKIP = (".git", ".metis", "Archive", "CROSS-LAYER", "VISUALIZATION", "_EVIDENCE", "_QUESTIONS", "_REGEN", "_PENDING", "_FEEDBACK")
HEAD = "# Generated by kb_coverage.py from CROSS-LAYER/LINK_GRAPH.yaml, the question register and the KB pages. Do not edit by hand.\n"
COUNTED = ("table", "view", "column", "endpoint", "screen", "component", "job", "business object", "class")


def page_files(kb):
    """{path relative to the KB: text} for every hand-written Markdown page (not generated, not in a skipped folder)."""
    out = {}
    for dirpath, dirnames, filenames in os.walk(kb):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP)
        for name in sorted(filenames):
            if not name.endswith(".md"):
                continue
            with open(os.path.join(dirpath, name), encoding="utf-8", errors="replace") as fh:
                text = fh.read()
            if "Generated by" in text[:300]:
                continue
            out[os.path.relpath(os.path.join(dirpath, name), kb).replace(os.sep, "/")] = text
    return out


def pages(kb):
    """Text of every hand-written Markdown page in the KB, lower-cased, as one string per page."""
    return [t.lower() for t in page_files(kb).values()]


def named(name, texts):
    """True if `name` appears in any of the lower-cased `texts` as a whole word (APP.ORDERS also matches ORDERS)."""
    n = str(name).lower()
    whole = re.compile(r"(?<!\w)%s(?!\w)" % re.escape(n))
    if any(whole.search(t) for t in texts):
        return True
    if "." in n:
        last = re.compile(r"(?<![\w.])%s(?!\w)" % re.escape(n.rsplit(".", 1)[1]))
        return any(last.search(t) for t in texts)
    return False


def load(path):
    if not os.path.isfile(path):
        return {}
    with open(path, encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


def build(kb):
    texts = pages(kb)
    g = load(os.path.join(kb, "CROSS-LAYER", "LINK_GRAPH.yaml"))
    nodes = {n["id"]: n for n in g.get("nodes") or []}
    unnamed, totals = {}, {}
    for n in sorted(nodes.values(), key=lambda n: n["id"]):
        if n["type"] not in COUNTED:
            continue
        totals[n["type"]] = totals.get(n["type"], 0) + 1
        if not named(n["name"], texts):
            unnamed.setdefault(n["type"], []).append(n["name"])
    reg = {}
    for p in (os.path.join(kb, "db", "DB_TABLE_REGISTRY.yaml"),):
        reg = load(p)
    tables = [t for t in reg.get("tables") or []]
    tables_unnamed = sorted(str(t.get("key") or t["name"]) for t in tables if not named(t["name"], texts))
    qs = [q for q in (load(os.path.join(kb, "_QUESTIONS", "VALIDATE_KB.yaml")).get("questions") or []) if q.get("status") == "open"]
    by_pri = {}
    blocked = {}
    for q in qs:
        by_pri[q.get("priority")] = by_pri.get(q.get("priority"), 0) + 1
        b = q.get("blocks") or []
        for f in (b if isinstance(b, list) else [b]):
            if f:
                blocked.setdefault(str(f), []).append(q["id"])
    skipped = gen_matrix.unrecognised(nodes, g.get("edges") or [])
    by_origin = {}
    for e in g.get("edges") or []:
        o = e.get("origin") or "unknown"
        by_origin[o] = by_origin.get(o, 0) + 1
    sql = load(os.path.join(kb, "CROSS-LAYER", "parsed.links.yaml"))
    sql_read = ({"files": sql.get("files", 0), "parsed": sql.get("parsed", 0), "not_parsed": sql.get("unparsed") or [],
                 "partly_read": sql.get("partial") or [], "links_dropped": len(sql.get("dropped") or [])}
                if sql else "sql_links.py has not been run (needs sqlglot)")
    try:  # page_owners reads gate.teams, CODEOWNERS and .metis/page_meta.yaml; a KB with none of them lists every page
        import page_owners
        no_owner = sorted(page_owners.files_without_owner(kb))
    except Exception:  # noqa: BLE001
        no_owner = None
    return {
        "as_of": datetime.date.today().isoformat(),
        "method": "name match against hand-written KB pages; see the top of tools/kb_coverage.py",
        "objects": {t: {"in_graph": totals[t], "named_in_no_page": len(unnamed.get(t, [])), "names": unnamed.get(t, [])}
                    for t in sorted(totals)},
        "catalogue_tables": {"in_registry": len(tables), "named_in_no_page": len(tables_unnamed), "names": tables_unnamed},
        "edges_by_origin": dict(sorted(by_origin.items())),
        "sql_read": sql_read,
        "rejected_links": g.get("rejected") or [],
        "impact_not_understood": skipped,
        "open_questions": {"total": len(qs), "by_priority": dict(sorted(by_pri.items(), key=lambda kv: str(kv[0]))),
                           "blocked_files": {k: v for k, v in sorted(blocked.items())}},
        "files_without_owner": ({"count": len(no_owner), "names": no_owner} if no_owner is not None else "not measured"),
        "not_measured": ["objects with no owner (no owner field in the graph)", "SQL in non-.sql files"],
    }


def summary(rep):
    objs = sum(v["named_in_no_page"] for v in rep["objects"].values())
    sql = rep["sql_read"]
    sql_txt = ("%d SQL files not parsed, %d partly read" % (len(sql["not_parsed"]), len(sql["partly_read"]))
               if isinstance(sql, dict) else "SQL not parsed")
    return ("%d graph objects named in no page, %d catalogue tables named in no page, %d rejected links, "
            "%d relations and %d node types the impact matrix cannot use, %s, %d open questions"
            % (objs, rep["catalogue_tables"]["named_in_no_page"], len(rep["rejected_links"]),
               len(rep["impact_not_understood"]["relations"]), len(rep["impact_not_understood"]["node_types"]),
               sql_txt, rep["open_questions"]["total"]))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("kb")
    a = ap.parse_args(argv)
    rep = build(a.kb)
    out = os.path.join(a.kb, "CROSS-LAYER")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "COVERAGE.yaml"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEAD)
        yaml.safe_dump(rep, fh, sort_keys=False, allow_unicode=True, width=120)
    print("coverage: " + summary(rep))
    return 0


if __name__ == "__main__":
    sys.exit(main())
