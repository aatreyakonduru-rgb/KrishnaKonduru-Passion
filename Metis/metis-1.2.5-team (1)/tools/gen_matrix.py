#!/usr/bin/env python3
"""Cross-layer impact matrix and QA coverage from the link graph.

    python3 gen_matrix.py <kb>

Reads CROSS-LAYER/LINK_GRAPH.yaml (gen_graph.py) and, if present, CROSS-LAYER/IMPACT_MATRIX.CURATED.yaml.
For every table, column, endpoint, screen, job and business object it lists what moves when that thing
changes: the direct dependents and the full chain, each step with the source of its link. Only links whose
relation has a known direction (DEPENDS below) are followed; any other link is listed as related, not
followed. Writes CROSS-LAYER/IMPACT_MATRIX.yaml and CROSS-LAYER/QA_COVERAGE.yaml.

Curated chains (hand-written) use: chains: [{start: {type, name}, steps: [{from, rel, to, source}], note}].
A curated chain is kept only if every step's source resolves.
"""
import argparse
import datetime
import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import verify_kb  # noqa: E402

# relation -> which end depends on the other ("from": the from-node moves when the to-node changes)
DEPENDS = {
    "reads": "from", "calls": "from", "handled by": "from", "uses": "from", "tests": "from",
    "joins": "both", "references": "from", "stored in": "from", "applies to": "from",
    "has column": "from", "part of": "to", "scheduled by": "from", "derived from": "from",
    "writes": "to", "runs": "to", "feeds": "to", "triggers": "to",
    # relations written by code_links.py: the importer or reader moves when what it imports or reads changes;
    # an endpoint moves when the class that exposes it changes
    "imports": "from", "reads table": "from", "writes table": "to", "exposes endpoint": "to",
}
ANCHORS = ("table", "view", "column", "endpoint", "screen", "component", "job", "business object", "class")
# node types written by code_links.py: they appear inside impact chains but get no entry of their own (a build with
# thousands of modules would otherwise write thousands of entries), so they are not reported as "not understood"
CHAIN_ONLY = ("module", "function")
COVER = ("screen", "endpoint", "business object", "table", "job")
HEAD = "# Generated by gen_matrix.py from CROSS-LAYER/LINK_GRAPH.yaml; every step names its source. Do not edit by hand.\n"


def load(path):
    if not os.path.isfile(path):
        return {}
    with open(path, encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


def norm_rel(rel):
    """`handled_by`, `Handled-By` and `handled by` are the same relation."""
    return " ".join(str(rel).lower().replace("_", " ").replace("-", " ").split())


def unrecognised(nodes, edges):
    """What the impact matrix cannot use: relation names with no direction and node types that get no entry.
    Returns {"relations": {name: count}, "node_types": {name: count}}; both empty when everything is understood."""
    rels, types = {}, {}
    for e in edges:
        if norm_rel(e["rel"]) not in DEPENDS:
            rels[str(e["rel"])] = rels.get(str(e["rel"]), 0) + 1
    for n in nodes.values():
        if n["type"] not in ANCHORS and n["type"] not in CHAIN_ONLY and n["type"] != "test":
            types[str(n["type"])] = types.get(str(n["type"]), 0) + 1
    return {"relations": rels, "node_types": types}


def dependents(edges):
    dep, related = {}, {}
    for e in edges:
        d = DEPENDS.get(norm_rel(e["rel"]))
        pairs = []
        if d in ("from", "both"):
            pairs.append((e["to"], e["from"]))
        if d in ("to", "both"):
            pairs.append((e["from"], e["to"]))
        if d is None:
            related.setdefault(e["from"], []).append(e)
            related.setdefault(e["to"], []).append(e)
        for changed, moves in pairs:
            dep.setdefault(changed, []).append((moves, e))
    return dep, related


def chain(start, dep, depth=int(os.environ.get("METIS_IMPACT_DEPTH", "3"))):
    seen, out, frontier = {start}, [], [(start, [])]
    for _ in range(depth):
        nxt = []
        for node, path in frontier:
            for moves, e in dep.get(node, []):
                if moves in seen:
                    continue
                seen.add(moves)
                p = path + [{"from": e["from"], "rel": e["rel"], "to": e["to"], "source": e["source"],
                             "origin": e.get("origin") or "unknown"}]
                out.append({"moves": moves, "via": p})
                nxt.append((moves, p))
        frontier = nxt
    return out


def build(kb):
    g = load(os.path.join(kb, "CROSS-LAYER", "LINK_GRAPH.yaml"))
    nodes = {n["id"]: n for n in g.get("nodes") or []}
    edges = g.get("edges") or []
    dep, related = dependents(edges)
    matrix = {}
    for nid, n in sorted(nodes.items()):
        if n["type"] not in ANCHORS:
            continue
        ch = chain(nid, dep)
        if not ch and nid not in related:
            continue
        by_type = {}
        for c in ch:
            by_type.setdefault(nodes.get(c["moves"], {}).get("type", "?"), []).append(c["moves"])
        matrix[nid] = {"type": n["type"], "name": n["name"], "moves_by_type": by_type, "chain": ch,
                       "related_not_followed": [{"from": e["from"], "rel": e["rel"], "to": e["to"],
                                                 "source": e["source"], "origin": e.get("origin") or "unknown"}
                                                for e in related.get(nid, [])]}
    chk = verify_kb.Checker(kb)
    curated, rejected = [], []
    for i, c in enumerate(load(os.path.join(kb, "CROSS-LAYER", "IMPACT_MATRIX.CURATED.yaml")).get("chains") or []):
        bad = []
        for s in c.get("steps") or []:
            tags = verify_kb.TAG.findall(str(s.get("source") or ""))
            if not tags or any(k != "E" for k, _ in tags):
                bad.append("step has no source tag (E:)")
            bad += [r for k, v in tags for part in v.split(";") for r in [chk.resolve(k, part)] if r]
        (rejected if bad or not c.get("steps") else curated).append(
            {"at": i, "reason": "; ".join(bad) or "no steps"} if bad or not c.get("steps") else c)
    tests = {}
    for e in edges:
        if norm_rel(e["rel"]) == "tests":
            tests.setdefault(e["to"], []).append({"test": e["from"], "source": e["source"]})
    tested_by = {}
    for t, lst in tests.items():
        for x in lst:
            tested_by.setdefault(t, []).append(dict(x, direct=True))
    for nid in nodes:
        for c in chain(nid, dep):
            if nodes.get(c["moves"], {}).get("type") == "test" and nid not in tests:
                tested_by.setdefault(nid, []).append({"test": c["moves"], "direct": False, "via": c["via"]})
    coverage = {}
    for nid, n in sorted(nodes.items()):
        if n["type"] in COVER:
            coverage.setdefault(n["type"], []).append({"id": nid, "name": n["name"], "tested_by": tested_by.get(nid, [])})
    return matrix, curated, rejected, coverage, any(n["type"] == "test" for n in nodes.values())


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("kb")
    a = ap.parse_args(argv)
    matrix, curated, rejected, coverage, has_tests = build(a.kb)
    g = load(os.path.join(a.kb, "CROSS-LAYER", "LINK_GRAPH.yaml"))
    skipped = unrecognised({n["id"]: n for n in g.get("nodes") or []}, g.get("edges") or [])
    out = os.path.join(a.kb, "CROSS-LAYER")
    os.makedirs(out, exist_ok=True)
    today = datetime.date.today().isoformat()
    with open(os.path.join(out, "IMPACT_MATRIX.yaml"), "w", encoding="utf-8") as fh:
        fh.write(HEAD)
        yaml.safe_dump({"as_of": today, "how_to_read": "entries.<type:name>.chain lists what moves when it changes; "
                        "each step names the link and its source", "directions": DEPENDS, "entries": matrix,
                        "curated": curated, "curated_rejected": rejected,
                        "not_understood": dict(skipped, note="relations here are listed as related, not followed; node types here "
                                               "get no entry. Rename the relation or add the type, or the impact is incomplete.")},
                       fh, sort_keys=False, allow_unicode=True, width=120)
    summary = {t: {"total": len(v), "tested": sum(1 for x in v if x["tested_by"])} for t, v in coverage.items()}
    with open(os.path.join(out, "QA_COVERAGE.yaml"), "w", encoding="utf-8") as fh:
        fh.write(HEAD)
        yaml.safe_dump({"as_of": today, "test_sources_read": has_tests, "summary": summary, "items": coverage},
                       fh, sort_keys=False, allow_unicode=True, width=120)
    print("%d impact entries, %d curated (%d rejected), coverage %s" % (len(matrix), len(curated), len(rejected), summary))
    if skipped["relations"] or skipped["node_types"]:
        print("WARNING impact is incomplete: relations not followed %s; node types with no entry %s"
              % (skipped["relations"] or "none", skipped["node_types"] or "none"), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
