#!/usr/bin/env python3
"""Parser-built links: which table reads which table, read from the SQL itself.

    python3 sql_links.py <kb> [--dialect snowflake] [--out FILE]

Reads every .sql file in the repos named under sources.repos in <kb>/.metis/kb-profile.yaml (read only), parses each with
sqlglot, and writes <kb>/CROSS-LAYER/parsed.links.yaml. No model is involved: a link is there because the parser saw the
table in the statement.

  - INSERT, CREATE ... AS, MERGE and UPDATE: the target table reads every other table in the statement.
  - A dbt model (a .sql file under a models/ folder) with a plain SELECT: the model, named by the file name, reads every
    table in it. `{{ ref('x') }}` and `{{ source('s','t') }}` are turned into table names first; other Jinja is
    replaced by a placeholder, and `{% ... %}` blocks are removed. Line numbers are kept.
  - CTE names are not tables. A table function or a templated name (`{{ this }}`) is not a table either.
  - A plain SELECT outside dbt has no target, so it gives no link; it is counted under `no_target`.
  - CREATE TABLE without a query: the tables its FOREIGN KEY ... REFERENCES clauses name become `references` links.
  - A statement sqlglot only reads as a bare command (unsupported syntax) gives no link; it is listed under `partial`.

Every link carries `[E: <repo>/<file>:<line> "<name as written>"]` and is checked with verify_kb before it is written;
one that does not resolve is dropped and listed under `dropped`. SQL that sqlglot cannot read is listed under `unparsed`
with the reason, so a missing link is never silent. Names are kept as written (case and qualification), so
`ORDERS` and `orders` are two nodes until a team settles on one spelling.

gen_graph.py marks every link in this file `origin: parsed`. The origin comes from the file's path, not from anything
inside it, so a hand-written link cannot claim it. Table-level only: no column lineage yet.
The dialect is --dialect, else `parse.dialect`, else `db.engine` in the profile (a name sqlglot knows), else sqlglot's own.
"""
import argparse
import datetime
import os
import re
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import verify_kb  # noqa: E402

OUT = os.path.join("CROSS-LAYER", "parsed.links.yaml")
SKIP_DIRS = {".git", "node_modules", "target", "build", "dist", "dbt_packages", ".venv", "venv", "__pycache__"}
MAX_BYTES = 2_000_000
PLACEHOLDER = "__jinja__"
HEAD = ("# Generated by sql_links.py by parsing the SQL files of the source repos with sqlglot. Do not edit by hand.\n"
        "# gen_graph.py marks every link in this file origin: parsed.\n")

CONFIG = re.compile(r"\{\{\s*config\s*\(.*?\)\s*\}\}", re.S)
BLOCK = re.compile(r"\{%.*?%\}|\{#.*?#\}", re.S)
REF = re.compile(r"""\{\{\s*ref\(\s*(?:['"][^'"]+['"]\s*,\s*)?['"]([^'"]+)['"]\s*(?:,[^)]*)?\)\s*\}\}""")
SOURCE = re.compile(r"""\{\{\s*source\(\s*['"]([^'"]+)['"]\s*,\s*['"]([^'"]+)['"]\s*\)\s*\}\}""")
ANY = re.compile(r"\{\{.*?\}\}", re.S)


def load_sqlglot():
    try:
        import sqlglot
        from sqlglot import exp
    except ImportError:
        return None, None
    return sqlglot, exp


def render(sql):
    """Turn dbt Jinja into plain SQL without changing the number of lines."""
    def blank(m):
        return "\n" * m.group(0).count("\n")

    def keep(text):
        return lambda m: text(m) + "\n" * (m.group(0).count("\n"))

    sql = CONFIG.sub(blank, sql)
    sql = BLOCK.sub(blank, sql)
    sql = REF.sub(keep(lambda m: m.group(1)), sql)
    sql = SOURCE.sub(keep(lambda m: "%s.%s" % m.groups()), sql)
    return ANY.sub(keep(lambda m: PLACEHOLDER), sql)


def table_name(t):
    parts = [p for p in (t.catalog, t.db, t.name) if p]
    return ".".join(parts)


def is_real_table(exp, t):
    return isinstance(t.this, exp.Identifier) and t.name and PLACEHOLDER not in t.name


LOST = ("INSERT", "CREATE", "MERGE", "UPDATE", "SELECT", "WITH", "REPLACE", "COPY")


def visible_ctes(exp, t):
    """Names of the CTEs a table reference can see. A CTE does not see itself or the ones after it, so
    `with a as (select * from a)` reads a real table called a."""
    names, child, node = set(), t, t.parent
    while node is not None:
        if isinstance(node, exp.CTE):
            siblings = node.parent.expressions if node.parent is not None else []
            for c in siblings:
                if c is node:
                    break
                if c.alias:
                    names.add(c.alias.lower())
        else:
            w = node.args.get("with_") or node.args.get("with")
            if w is not None and child is not w:
                names |= {c.alias.lower() for c in w.expressions if c.alias}
        child, node = node, node.parent
    return names


def statements(sqlglot, exp, text, dialect):
    """([{target: (name, kind) or None, rel, sources: [(name, line)]}], number of statements read only as a bare command)."""
    out, lost = [], 0
    for stmt in sqlglot.parse(text, read=dialect):
        if stmt is None:
            continue
        if isinstance(stmt, exp.Command):
            lost += 1 if str(stmt.this).upper() in LOST else 0
            continue
        target = None
        if isinstance(stmt, (exp.Insert, exp.Create, exp.Merge, exp.Update)):
            first = stmt.this.find(exp.Table) if stmt.this is not None else None
            if first is not None and is_real_table(exp, first):
                kind = str(stmt.args.get("kind") or "").upper() if isinstance(stmt, exp.Create) else ""
                target = (table_name(first), "view" if kind == "VIEW" else "table", first)
        # CREATE TABLE without a query only names other tables through FOREIGN KEY ... REFERENCES
        rel = "references" if isinstance(stmt, exp.Create) and stmt.args.get("expression") is None else "reads"
        sources, seen = [], set()
        for t in stmt.find_all(exp.Table):
            if not is_real_table(exp, t) or (target and t is target[2]):
                continue
            name = table_name(t)
            if not t.db and not t.catalog and name.lower() in visible_ctes(exp, t):
                continue
            if name in seen or (target and name == target[0]):
                continue
            seen.add(name)
            sources.append((name, t.this.meta.get("line")))
        out.append({"target": target[:2] if target else None, "rel": rel, "sources": sources})
    return out, lost


def sql_files(base):
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in sorted(filenames):
            if name.lower().endswith(".sql"):
                yield os.path.join(dirpath, name)


def quote_for(name, lines_text):
    for cand in (name, name.rsplit(".", 1)[-1]):
        if cand and '"' not in cand and "]" not in cand and cand in lines_text:
            return cand
    return None


def build(kb, dialect=None):
    sqlglot, exp = load_sqlglot()
    if sqlglot is None:
        raise RuntimeError("sqlglot is not installed (pip install sqlglot)")
    chk = verify_kb.Checker(kb)
    dialect = dialect or (chk.settings.get("parse") or {}).get("dialect") or (chk.settings.get("db") or {}).get("engine")
    try:
        sqlglot.Dialect.get_or_raise(dialect)
    except Exception:
        dialect = None
    import logging
    logging.getLogger("sqlglot").setLevel(logging.ERROR)
    parsed, unparsed, no_target, partial, seen_files = {}, [], [], [], 0
    for repo in sorted(chk.repos):
        base, err = chk.repo_path(repo + "/x")
        if err:
            continue
        base = os.path.dirname(base)
        if not os.path.isdir(base):
            continue
        for path in sql_files(base):
            rel = "%s/%s" % (repo, os.path.relpath(path, base).replace(os.sep, "/"))
            seen_files += 1
            if os.path.getsize(path) > MAX_BYTES:
                unparsed.append({"file": rel, "reason": "file is over %d bytes" % MAX_BYTES})
                continue
            with open(path, encoding="utf-8", errors="replace") as fh:
                original = fh.read()
            try:
                stmts, lost = statements(sqlglot, exp, render(original), dialect)
                parsed[rel] = (original, stmts)
                if lost:
                    partial.append({"file": rel, "statements": lost,
                                    "reason": "read only as a bare command (unsupported syntax); their tables are not linked"})
            except Exception as exc:
                unparsed.append({"file": rel, "reason": "%s: %s" % (type(exc).__name__, str(exc).splitlines()[0][:160])})
    views = {t[0] for _, stmts in parsed.values() for s in stmts for t in [s["target"]] if t and t[1] == "view"}

    def node(name):
        return {"type": "view" if name in views else "table", "name": name}

    links, dropped = [], []
    for rel in sorted(parsed):
        original, stmts = parsed[rel]
        lines = original.splitlines()
        dbt = "models" in rel.split("/")[:-1]
        stem = os.path.splitext(rel.rsplit("/", 1)[-1])[0]
        made, any_target = set(), False
        for s in stmts:
            target = s["target"] or ((stem, "table") if dbt and s["sources"] else None)
            if not target:
                continue
            any_target = True
            for name, line in s["sources"]:
                if (target[0], name) in made:
                    continue
                if not line or line > len(lines):
                    dropped.append({"file": rel, "name": name, "why": "no usable line number"})
                    continue
                q = quote_for(name, lines[line - 1])
                if not q:
                    dropped.append({"file": rel, "line": line, "name": name, "why": "name not found on that line of the file"})
                    continue
                src = '[E: %s:%d "%s"]' % (rel, line, q)
                why = chk.resolve("E", src[4:-1])
                if why:
                    dropped.append({"file": rel, "line": line, "name": name, "why": why})
                    continue
                made.add((target[0], name))
                links.append({"from": node(target[0]), "rel": s["rel"], "to": node(name), "source": src})
        if stmts and not any_target and any(s["sources"] for s in stmts):
            no_target.append(rel)
    return {"dialect": dialect or "sqlglot default", "sqlglot": sqlglot.__version__, "files": seen_files, "parsed": len(parsed),
            "links": links, "unparsed": unparsed, "partial": partial, "no_target": no_target, "dropped": dropped}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("kb")
    ap.add_argument("--dialect")
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    out = a.out or os.path.join(a.kb, OUT)
    try:
        res = build(a.kb, a.dialect)
    except RuntimeError as exc:
        print("cannot parse SQL: %s" % exc, file=sys.stderr)
        return 2
    if res["files"] == 0:
        if os.path.isfile(out):
            os.remove(out)
        print("no .sql files in the source repos; no parsed links")
        return 0
    os.makedirs(os.path.dirname(out), exist_ok=True)
    data = {"as_of": datetime.date.today().isoformat()}
    data.update(res)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEAD)
        yaml.safe_dump(data, fh, sort_keys=False, allow_unicode=True, width=120)
    print("%d SQL files, %d parsed, %d not parsed, %d partly read, %d links, %d dropped, %d with no target -> %s"
          % (res["files"], res["parsed"], len(res["unparsed"]), len(res["partial"]), len(res["links"]), len(res["dropped"]),
             len(res["no_target"]), out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
