import os
import shutil
import sys
import tempfile
import unittest

import yaml

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import kb_coverage  # noqa: E402


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


class Coverage(unittest.TestCase):
    def setUp(self):
        self.kb = tempfile.mkdtemp()
        graph = {"nodes": [{"id": "table:APP.ORDERS", "type": "table", "name": "APP.ORDERS"},
                           {"id": "table:APP.SECRET", "type": "table", "name": "APP.SECRET"},
                           {"id": "endpoint:GET /orders", "type": "endpoint", "name": "GET /orders"},
                           {"id": "dbt_model:m", "type": "dbt_model", "name": "m"}],
                 "edges": [{"from": "endpoint:GET /orders", "rel": "reads", "to": "table:APP.ORDERS", "source": "[E: a:1]"},
                           {"from": "endpoint:GET /orders", "rel": "maps_to", "to": "dbt_model:m", "source": "[E: a:2]"}],
                 "rejected": [{"at": "m/x.links.yaml#3", "reason": "link has no source tag (E:)"}]}
        write(os.path.join(self.kb, "CROSS-LAYER/LINK_GRAPH.yaml"), yaml.safe_dump(graph))
        write(os.path.join(self.kb, "m/orders.md"), "# Orders\nThe orders table reads APP.ORDERS and serves GET /orders.\n")
        write(os.path.join(self.kb, "m/gen.md"), "# Generated by gen_x.py\nAPP.SECRET is listed here.\n")
        write(os.path.join(self.kb, "db/DB_TABLE_REGISTRY.yaml"), yaml.safe_dump({"tables": [
            {"key": "D.APP.ORDERS", "name": "ORDERS"}, {"key": "D.APP.AUDIT", "name": "AUDIT"}]}))
        write(os.path.join(self.kb, "_QUESTIONS/VALIDATE_KB.yaml"), yaml.safe_dump({"questions": [
            {"id": "Q-0001", "status": "open", "priority": "P1", "blocks": ["m/orders.md"]},
            {"id": "Q-0002", "status": "answered", "priority": "P2", "blocks": ["m/orders.md"]}]}))

    def tearDown(self):
        shutil.rmtree(self.kb)

    def test_names_in_no_hand_written_page_are_listed(self):
        rep = kb_coverage.build(self.kb)
        self.assertEqual(rep["objects"]["table"]["names"], ["APP.SECRET"])  # only a generated page mentions it
        self.assertEqual(rep["objects"]["endpoint"]["named_in_no_page"], 0)
        self.assertEqual(rep["catalogue_tables"]["names"], ["D.APP.AUDIT"])

    def test_rejected_links_unknown_relations_and_open_questions_are_reported(self):
        rep = kb_coverage.build(self.kb)
        self.assertEqual(len(rep["rejected_links"]), 1)
        self.assertEqual(rep["impact_not_understood"]["relations"], {"maps_to": 1})
        self.assertEqual(rep["impact_not_understood"]["node_types"], {"dbt_model": 1})
        self.assertEqual(rep["open_questions"]["total"], 1)
        self.assertEqual(rep["open_questions"]["blocked_files"], {"m/orders.md": ["Q-0001"]})

    def test_writes_the_report_and_an_empty_kb_does_not_crash(self):
        self.assertEqual(kb_coverage.main([self.kb]), 0)
        self.assertTrue(os.path.isfile(os.path.join(self.kb, "CROSS-LAYER/COVERAGE.yaml")))
        empty = tempfile.mkdtemp()
        try:
            self.assertEqual(kb_coverage.main([empty]), 0)
        finally:
            shutil.rmtree(empty)


if __name__ == "__main__":
    unittest.main()
