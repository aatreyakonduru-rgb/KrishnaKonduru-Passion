import os
import shutil
import subprocess
import sys
import tempfile
import unittest

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(HERE, "..", "ui"))
import answers  # noqa: E402
import build_plan  # noqa: E402
import views  # noqa: E402


def write(p, text):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def git(repo, *args):
    subprocess.run(["git", "-C", repo, "-c", "user.name=t", "-c", "user.email=t@t", *args], check=True, capture_output=True)


SQL = "CREATE TABLE orders (\n  order_id INT PRIMARY KEY,\n  status VARCHAR(20)\n);\n"
Q = "orders status column"


@unittest.skipUnless(shutil.which("git"), "git not installed")
class Fresh(unittest.TestCase):
    def setUp(self):
        self.d = tempfile.mkdtemp()
        self.repo = os.path.join(self.d, "repo")
        self.kb = os.path.join(self.d, "kb")
        write(os.path.join(self.repo, "schema.sql"), SQL)
        git(self.repo, "init", "-q")
        git(self.repo, "add", "-A")
        git(self.repo, "commit", "-q", "-m", "one")
        write(os.path.join(self.kb, ".metis", "kb-profile.yaml"),
              yaml.safe_dump({"sources": {"workspace_root": self.d, "repos": {"repo": "repo"}}}))
        write(os.path.join(self.kb, "db", "ORDERS.md"),
              '# Orders\n\n- The orders table has a status column of type VARCHAR(20). [E: repo/schema.sql:3-3 "status VARCHAR(20)"]\n')
        write(os.path.join(self.kb, "CROSS-LAYER", "LINK_GRAPH.yaml"),
              "# Generated by gen_graph.py\nas_of: '2026-11-12'\nnodes:\n- {id: 'table:orders', type: table, name: orders}\nedges: []\n")

    def tearDown(self):
        shutil.rmtree(self.d, ignore_errors=True)

    def change_source(self):
        write(os.path.join(self.repo, "schema.sql"), SQL.replace("VARCHAR(20)", "VARCHAR(40)"))
        git(self.repo, "add", "-A")
        git(self.repo, "commit", "-q", "-m", "two")

    def test_unchanged_source_is_fresh_and_high(self):
        build_plan.record(self.kb)
        r = answers.ask(self.kb, Q, "Pat Lee")
        self.assertTrue(r["freshness"]["checked"])
        self.assertEqual(r["freshness"]["stale"], [])
        self.assertEqual(r["confidence"]["band"], "High")
        self.assertEqual(views.freshness_note(r["freshness"]), "")

    def test_changed_source_is_flagged_and_never_high(self):
        build_plan.record(self.kb)
        self.change_source()
        r = answers.ask(self.kb, Q, "Pat Lee")
        self.assertEqual([x["page"] for x in r["freshness"]["stale"]], ["db/ORDERS.md"])
        self.assertNotEqual(r["confidence"]["band"], "High")
        self.assertTrue(any("changed since the KB was built" in x for x in r["confidence"]["reasons"]))
        note = views.freshness_note(r["freshness"])
        self.assertIn("Source changed", note)
        self.assertIn("db/ORDERS.md", note)

    def test_the_answer_itself_is_still_given(self):
        build_plan.record(self.kb)
        self.change_source()
        r = answers.ask(self.kb, Q, "Pat Lee")
        self.assertGreaterEqual(r["checked"]["lines"], 1)  # flagged, not withheld: the reader decides

    def test_no_recorded_build_is_unknown_not_stale(self):
        r = answers.ask(self.kb, Q, "Pat Lee")
        self.assertEqual(r["freshness"]["stale"], [])
        self.assertEqual(r["freshness"]["unknown"], ["repo"])
        self.assertEqual(r["confidence"]["band"], "High")
        self.assertIn("no recorded build commit", views.freshness_note(r["freshness"]))

    def test_a_page_not_used_does_not_count(self):
        write(os.path.join(self.kb, "db", "OTHER.md"),
              '# Other\n\n- The billing ledger rounds amounts. [E: repo/schema.sql:2-2 "order_id INT PRIMARY KEY"]\n')
        build_plan.record(self.kb)
        self.change_source()
        r = answers.ask(self.kb, "orders status column", "Pat Lee")
        self.assertNotIn("db/OTHER.md", [x["page"] for x in r["freshness"]["stale"]])

    def test_no_profile_gives_no_warning_and_no_failure(self):
        os.remove(os.path.join(self.kb, ".metis", "kb-profile.yaml"))
        f = answers.freshness(self.kb, ["db/ORDERS.md"])
        self.assertEqual(f["stale"], [])
        self.assertEqual(views.freshness_note(f) if f["checked"] else "", "")


if __name__ == "__main__":
    unittest.main()
