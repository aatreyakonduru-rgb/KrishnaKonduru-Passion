def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


class Parts(unittest.TestCase):
    def test_slugs_follow_github_rules_and_repeat_suffixes(self):
        a = L.anchors("# Claim Intake (v2)\n\n## Rules & Limits\n\n## Rules & Limits\n\n## `code` name\n\n<a id=\"custom\"></a>\n")
        self.assertTrue({"claim-intake-v2", "rules--limits", "rules--limits-1", "code-name", "custom", "top"} <= a)

    def test_links_skip_code_and_tags_and_find_reference_definitions(self):
        t = ("- see [a](a.md) and [b](b.md#x \"title\") and `[no](code.md)` [E: file:r.txt \"q\"]\n```\n[c](c.md)\n```\n"
             "[ref]: ref.md\n[W](https://x.org/a.md)\n")
        self.assertEqual([(n, x) for n, _, x in L.links(t)], [(1, "a.md"), (1, "b.md#x"), (5, "ref.md"), (6, "https://x.org/a.md")])

    def test_resolve_cases(self):
        kb = tempfile.mkdtemp()
        try:
            write(os.path.join(kb, "a", "p.md"), "x\n")
            write(os.path.join(kb, "top.md"), "x\n")
            self.assertEqual(L.resolve(kb, "a/q.md", "p.md")[::2], ("ok", "a/p.md"))
            self.assertEqual(L.resolve(kb, "a/q.md", "../top.md#h")[:2], ("ok", "h"))
            self.assertEqual(L.resolve(kb, "a/q.md", "/top.md")[2], "top.md")
            self.assertEqual(L.resolve(kb, "a/q.md", "nope.md")[0], "missing-file")
            self.assertEqual(L.resolve(kb, "a/q.md", "../../x.md")[0], "outside-kb")
            self.assertEqual(L.resolve(kb, "a/q.md", "mailto:a@b.c")[0], "external")
            self.assertEqual(L.resolve(kb, "a/q.md", "#h")[2], "a/q.md")
            self.assertEqual(L.resolve(kb, "a/q.md", "<p.md>")[0], "ok")
        finally:
            shutil.rmtree(kb, ignore_errors=True)


class Check(unittest.TestCase):
    def setUp(self):
        self.kb = tempfile.mkdtemp()
        write(os.path.join(self.kb, "README.md"), "# KB\n\n- [Rules](context/rules.md)\n")
        write(os.path.join(self.kb, "context", "rules.md"),
              "# Rules\n\n## Payment\n\n- Paid in 30 days [E: file:r.txt]. See [claims](../db/claims.md#columns) and [intake](intake.md).\n"
              "- Broken: [gone](missing.md), [bad anchor](../db/claims.md#nope), [out](../../../x.md), [self](#payment), [self2](#nowhere).\n"
              "- Web [site](https://example.com/a.md) is not checked.\n")
        write(os.path.join(self.kb, "db", "claims.md"), "# Claims\n\n## Columns\n\n- text [E: file:r.txt]\n")
        write(os.path.join(self.kb, "context", "intake.md"), "# Intake\n\n- text [E: file:r.txt]\n")
        write(os.path.join(self.kb, "context", "lonely.md"), "# Lonely\n\n- nobody links here [E: file:r.txt]\n")
        write(os.path.join(self.kb, "context", "indexed.md"), "# Indexed\n\n- listed only by path [E: file:r.txt]\n")
        write(os.path.join(self.kb, "context", "INDEX.md"), "# Index\n\n- context/indexed.md\n")
        write(os.path.join(self.kb, "db", "gen.md"), "# Generated by gen_x.py\n\n- generated and unlinked\n")
        write(os.path.join(self.kb, "_EVIDENCE", "files", "r.txt"), "x\n")
        write(os.path.join(self.kb, "_EVIDENCE", "bad.md"), "[x](nowhere.md)\n")

    def tearDown(self):
        shutil.rmtree(self.kb, ignore_errors=True)

    def test_broken_links_found_and_good_ones_pass(self):
        rep = L.check(self.kb)
        got = sorted((b["page"], b["problem"], b["target"]) for b in rep["broken"])
        self.assertEqual(got, [("context/rules.md", "missing-anchor", "#nowhere"),
                               ("context/rules.md", "missing-anchor", "../db/claims.md#nope"),
                               ("context/rules.md", "missing-file", "missing.md"),
                               ("context/rules.md", "outside-kb", "../../../x.md")])
        self.assertEqual(rep["broken_links"], 4)
        self.assertEqual(rep["links_checked"], 8)

    def test_orphans_exclude_linked_indexed_generated_index_and_root_pages(self):
        self.assertEqual(L.check(self.kb)["orphans"], ["context/lonely.md"])

    def test_evidence_folder_is_not_read(self):
        self.assertNotIn("_EVIDENCE/bad.md", [b["page"] for b in L.check(self.kb)["broken"]])

    def test_report_and_exit_code(self):
        self.assertEqual(L.main(["check", self.kb]), 1)
        rep = L.load_report(self.kb)
        self.assertEqual(rep["broken_links"], 4)
        res = verify_kb.Checker(self.kb).run()
        self.assertEqual([p for p in res["problems"] if p["file"].endswith("LINK_CHECK.yaml")], [])
        write(os.path.join(self.kb, "context", "rules.md"), "# Rules\n\n- ok [claims](../db/claims.md#columns) [E: file:r.txt]\n")
        self.assertEqual(L.main(["check", self.kb, "--no-write"]), 0)

    def test_nothing_is_edited(self):
        with open(os.path.join(self.kb, "context", "rules.md"), encoding="utf-8") as fh:
            before = fh.read()
        L.main(["check", self.kb])
        with open(os.path.join(self.kb, "context", "rules.md"), encoding="utf-8") as fh:
            self.assertEqual(fh.read(), before)
        with open(os.path.join(self.kb, "CROSS-LAYER", "LINK_CHECK.yaml"), encoding="utf-8") as fh:
            self.assertIn("broken", yaml.safe_load(fh))


if __name__ == "__main__":
    unittest.main()
