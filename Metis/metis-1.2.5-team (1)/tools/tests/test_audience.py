def write(p, text):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


SQL = ("CREATE TABLE orders (\n  order_id INT PRIMARY KEY,\n  customer_id INT,\n  status VARCHAR(20)\n);\n")
Q = "orders status"


class AudienceBase(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.d = tempfile.mkdtemp()
        cls.kb = os.path.join(cls.d, "kb")
        write(os.path.join(cls.d, "repo", "schema.sql"), SQL)
        prof = {"sources": {"workspace_root": cls.d, "repos": {"repo": "repo"}},
                "audience": {"people": {"Dana Kim": "business", "Lee Ortiz": "architect", "Sam Roe": "dev"}, "default": None}}
        write(os.path.join(cls.kb, ".metis", "kb-profile.yaml"), yaml.safe_dump(prof))
        write(os.path.join(cls.kb, "glossary", "TERMS.md"),
              '# Terms\n\n- An order status is the business state of an order: open, shipped or closed. [E: repo/schema.sql:4-4 "status VARCHAR(20)"]\n')
        write(os.path.join(cls.kb, "requirements", "ORDER_RULES.md"),
              '# Order rules\n\n- An order status must be set before an order is shipped. [E: repo/schema.sql:4-4 "status VARCHAR(20)"]\n')
        write(os.path.join(cls.kb, "architecture", "ORDER_FLOW.md"),
              '# Order flow\n\n- The orders service owns order status and publishes it to billing. [E: repo/schema.sql:1-1 "CREATE TABLE orders"]\n')
        write(os.path.join(cls.kb, "db", "ORDERS_DB.md"),
              '# Orders table\n\n- The orders table has a status column of type VARCHAR(20). [E: repo/schema.sql:4-4 "status VARCHAR(20)"]\n')
        write(os.path.join(cls.kb, "CROSS-LAYER", "LINK_GRAPH.yaml"),
              "# Generated by gen_graph.py from *.links.yaml\nas_of: '2026-11-12'\nnodes:\n- {id: 'table:orders', type: table, name: orders}\nedges: []\n")

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.d, ignore_errors=True)

    def pages(self, **kw):
        text, n, _ = answers.compose(self.kb, Q, **kw)
        return [ln for ln in text.splitlines() if ln.startswith("- ")], n


class Layers(AudienceBase):
    def test_layer_from_folder_and_front_matter(self):
        self.assertEqual(audience.layer_of("glossary/TERMS.md")[0], "meaning")
        self.assertEqual(audience.layer_of("requirements/X.md")[0], "rules")
        self.assertEqual(audience.layer_of("architecture/X.md")[0], "design")
        self.assertEqual(audience.layer_of("db/X.md")[0], "code")
        self.assertEqual(audience.layer_of("db/X.md", "---\nlayer: meaning\n---\n# x\n"), ("meaning", "front matter"))
        self.assertEqual(audience.layer_of("misc/X.md", "# nothing")[1], "default")

    def test_who_uses_profile_then_alias_then_none(self):
        self.assertEqual(audience.resolve(self.kb, "Dana Kim")["id"], "business")
        self.assertEqual(audience.resolve(self.kb, "Sam Roe")["id"], "developer")
        self.assertEqual(audience.resolve(self.kb, "tech lead")["id"], "tech_lead")
        self.assertIsNone(audience.resolve(self.kb, "Unmapped Person"))
        self.assertEqual(audience.resolve(self.kb, "Unmapped Person", "architect")["id"], "architect")

    def test_unknown_audience_is_an_error(self):
        with self.assertRaises(audience.AudienceError):
            audience.get("wizard")


class Ask(AudienceBase):
    def test_same_lines_different_order(self):
        biz, nb = self.pages(audience="business")
        dev, nd = self.pages(audience="developer")
        arch, na = self.pages(audience="architect")
        self.assertEqual(sorted(biz), sorted(dev))
        self.assertEqual(sorted(biz), sorted(arch))
        self.assertEqual((nb, nd, na), (nb, nb, nb))
        self.assertIn("business state", biz[0])          # meaning layer first
        self.assertIn("VARCHAR(20)", dev[0])              # code layer first
        self.assertIn("orders service", arch[0])          # design layer first
        self.assertNotEqual([biz[0], dev[0], arch[0]], [biz[0]] * 3)

    def test_profile_mapping_picks_the_lens_for_the_asker(self):
        by_person, _ = self.pages(who="Dana Kim")
        explicit, _ = self.pages(audience="business")
        self.assertEqual(by_person, explicit)

    def test_no_audience_keeps_the_old_order(self):
        none1, _ = self.pages()
        none2, _ = self.pages(who="Unmapped Person")
        self.assertEqual(none1, none2)

    def test_every_audience_answer_passes_the_source_check(self):
        for who in audience.AUDIENCES:
            text, _, _ = answers.compose(self.kb, Q, audience=who)
            p = os.path.join(self.d, "ans_%s.md" % who)
            write(p, text)
            rep = verify_kb.Checker(self.kb).check_answer(p)
            self.assertEqual(rep["problems"], [], (who, rep["problems"]))

    def test_info_says_what_the_lens_did(self):
        info = {}
        answers.compose(self.kb, Q, audience="business", info=info)
        self.assertEqual(info["audience"], "business")
        self.assertIn("Business", info["describe"])
        self.assertEqual(set(info["layers"].values()), {"meaning", "rules", "design", "code"})

    def test_single_layer_answer_says_the_audience_made_no_difference(self):
        import views
        info = {}
        answers.compose(self.kb, "orders table status column type", audience="business", info=info)
        self.assertEqual(info["layers_used"], sorted(set(info["layers"].values())))
        one = dict(info, layers_used=["code"])
        self.assertIn("same for every audience", views.audience_note(one))
        self.assertNotIn("same for every audience", views.audience_note(dict(info, layers_used=["code", "meaning"])))

    def test_cap_reports_what_was_left_out(self):
        old = answers.MAX_FACTS
        answers.MAX_FACTS = 2
        try:
            info = {}
            lines, _ = self.pages(audience="business", info=info)
            self.assertEqual(len(lines), 2)
            self.assertEqual(sum(info["left_out"].values()), 2)
            self.assertTrue(set(info["left_out"]) <= {"design", "code"})  # business keeps meaning and rules; the rest did not fit
        finally:
            answers.MAX_FACTS = old

    def test_bad_audience_in_ask_is_refused_and_writes_nothing(self):
        before = len(answers.all_asks(self.kb))
        with self.assertRaises(answers.C.UiError):
            answers.ask(self.kb, Q, "Pat Lee", audience="wizard")
        self.assertEqual(len(answers.all_asks(self.kb)), before)

    def test_ask_records_the_audience_and_never_hides_a_line(self):
        r = answers.ask(self.kb, Q, "Pat Lee", audience="architect")
        self.assertEqual(r["audience"]["audience"], "architect")
        self.assertEqual(r["checked"]["problems"], [])
        self.assertEqual(r["checked"]["lines"], 4)


class Pack(AudienceBase):
    def build(self, **kw):
        return context_pack.build(self.kb, task="order status", budget=4000, signals=False, stale_marks=False, **kw)

    def test_same_pages_different_order(self):
        biz, dev = self.build(audience="business"), self.build(audience="developer")
        self.assertEqual(sorted(biz["files"]), sorted(dev["files"]))
        self.assertEqual(biz["audience"], "business")
        self.assertTrue(biz["files"][0].startswith(("glossary", "requirements")), biz["files"])
        # the lens is a multiplier on relevance, so it moves a page up but cannot bury the best search hit:
        self.assertLess(dev["files"].index("db/ORDERS_DB.md"), biz["files"].index("db/ORDERS_DB.md"))
        self.assertLess(biz["files"].index("requirements/ORDER_RULES.md"), dev["files"].index("requirements/ORDER_RULES.md"))
        self.assertEqual(dev["layers"]["db/ORDERS_DB.md"], "code")

    def test_pack_ids_differ_by_audience_and_text_names_the_lens(self):
        biz, dev = self.build(audience="business"), self.build(audience="developer")
        self.assertNotEqual(biz["pack_id"], dev["pack_id"])
        self.assertIn("ordered for Business", biz["text"])

    def test_no_audience_is_unchanged(self):
        self.assertIsNone(self.build()["audience"])
        self.assertEqual(self.build()["pack_id"], self.build()["pack_id"])

    def test_bad_audience_is_a_pack_error(self):
        with self.assertRaises(context_pack.PackError):
            self.build(audience="wizard")


